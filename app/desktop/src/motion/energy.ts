import { useEffect, useRef } from "react";
import { animate, useMotionValue, useReducedMotion, type MotionValue } from "motion/react";
import { spring } from "./system";

/**
 * حقل طاقة التركيز — «الطاقة تسافر، ولا تنتقل آنياً».
 *
 * ما كان قائماً بعد الفصل الأول: الطاقة دالّة في **المسافة الصحيحة** عن
 * البلاطة المركَّزة. أي أنّ الانتقال من البلاطة 3 إلى 5 كان يعني: كلّ
 * بلاطة تحسب مسافتها الجديدة دفعةً واحدة ثم تستوفي إليها. البلاطة 4 —
 * التي تقع في **طريق** الطاقة — لم يكن يحدث لها شيء خاصّ؛ حسبت أنّ
 * مسافتها بقيت 1 فبقيت كما هي.
 *
 * وهذا بالضبط ما يمنعه هذا الفصل: الطاقة لا تُطفأ هنا وتُشعل هناك.
 *
 * ما صار: الطاقة لها **موضع متّصل** على الصفّ — عدد كسري ينزلق بنابض من
 * البلاطة القديمة إلى الجديدة. وكل بلاطة تقيس بُعدها عن هذا الموضع
 * المتحرّك لا عن الفهرس المستقرّ. فحين تمرّ الطاقة فوق البلاطة 4 تضيء
 * وهي تمرّ ثم تخبو خلفها.
 *
 * ثمنه صفر تقريباً: الموضع MotionValue خارج شجرة React، والبلاطات تشتقّ
 * منه بـ`useTransform` فتُكتب أنماطها كل إطار بلا إعادة عرض واحدة.
 */

/**
 * الطاقة عند مسافات صحيحة — نفس القيم المقيسة إطاراً بإطار.
 * ما بينها يُستوفى خطياً، فيبقى السلوك عند الاستقرار مطابقاً تماماً لما
 * كان، ويصير له معنى أثناء الحركة.
 */
const SAMPLES = [1, 0.6, 0.28, 0] as const;

/** أبعد من هذا لا طاقة — حدّ التأثير. */
export const ENERGY_REACH = SAMPLES.length - 1;

export function focusEnergy(distance: number): number {
  const d = Math.max(0, distance);
  if (d >= ENERGY_REACH) return 0;
  const i = Math.floor(d);
  const t = d - i;
  return SAMPLES[i] + (SAMPLES[i + 1] - SAMPLES[i]) * t;
}

/**
 * الاستجابة البصرية المشتقّة من الطاقة — لا تُكتب أي قيمة منها يدوياً.
 *
 * **الضبابية أُسقطت.** كانت تبلغ 1.1px على البلاطات البعيدة بحجّة «عمق
 * ميداني»، وسقوطها لسببين يتفقان:
 *
 * ① **المرجع لا يموّه.** البلاطة غير المركَّزة في واجهة الكونسول تبقى
 *    حادّةً تماماً؛ ما يفصلها عن المركَّزة هو الحجم والوضوح والظلّ لا
 *    نعومة الحواف. والتمويه كان إضافةً منّا لا محاكاةً للمرجع — وهو يجعل
 *    الرموز تبدو خارج البؤرة، وهو أثرٌ فوتوغرافي لا أثرُ واجهة.
 *
 * ② **هي أغلى ما في الشاشة.** `filter: blur()` التفافٌ حقيقي: يفرض رسم
 *    شجرة البلاطة كاملةً في نسيجٍ مستقلّ ثم تمريرَ نواة التمويه عليه —
 *    **في كل إطار تتغيّر فيه القيمة**، أي على ثماني بلاطات طوال كل تنقّل.
 *    والسطوع الباقي مرشّح مصفوفة لونية، وكلفته جزءٌ يسير من ذلك.
 *
 * التسلسل الهرمي لم يضعف: عُوّض بخفض الشفافية والسطوع قليلاً، ويبقى
 * الحجم (1.42×) والظلّ والحافّة والانعكاس والهالة تفصل المركَّزة عن
 * جيرانها بستّ قنوات أخرى.
 */
export interface EnergyResponse {
  opacity: number;
  brightness: number;
  badge: number;
}

export function energyResponse(energy: number): EnergyResponse {
  const e = Math.min(1, Math.max(0, energy));
  return {
    /*
     * **قاع الشفافية 0.8 — رقم المرجع حرفياً.**
     *
     * تذكره الوثيقة ثلاث مرّات مستقلّة: «‏setting its neighbors'
     * focus-energy lower (e.g. 0.8)»، و«‏opacity might drop to ~0.8»،
     * و«‏dimming unselected tiles to 80% opacity». دليلٌ لا يُردّ.
     *
     * وكنّا عند 0.62 — تعتيمٌ أعمق بكثير. وسببه أنّنا كنّا نعوّض به عن
     * حجمٍ مقصوص؛ فلمّا عاد الحجم إلى قياسه، عاد التعتيم إلى قدره.
     *
     * والسطوع يتبعه: قاعُه 0.88 بدل 0.8، فتبقى البلاطات البعيدة **مقروءة
     * تماماً** كما هي في لقطة المرجع — لا مطفأة. التسلسل الهرمي مصدره
     * الحجم، والضوء يؤكّده ولا يحمله وحده.
     */
    opacity: 0.8 + 0.2 * e,
    brightness: 0.88 + 0.12 * e,
    /* الشارة تخبو أسرع من البلاطة: شاراتٌ متساوية الوضوح فوق صفّ كامل
       ضجيجٌ بصري يزاحم ما يُنظر إليه فعلاً. */
    badge: 0.28 + 0.72 * Math.pow(e, 1.5),
  };
}

/**
 * المسافة على **حلقة**: من آخر بلاطة إلى الأولى خطوة واحدة لا ثماني.
 * تقبل موضعاً كسرياً، فهي صالحة أثناء السفر لا عند الاستقرار فقط.
 */
export function ringDistance(index: number, position: number, count: number): number {
  if (count <= 0) return Math.abs(index - position);
  const raw = Math.abs(index - (((position % count) + count) % count));
  return Math.min(raw, count - raw);
}

/**
 * أقصر إزاحة مُوقَّعة بين فهرسين على حلقة.
 * ضرورية كي لا تجتاح الطاقةُ الصفَّ كلّه عند الالتفاف: من البلاطة الثامنة
 * إلى الأولى المسافة خطوة واحدة إلى الأمام، لا ثماني خطوات إلى الوراء.
 */
export function shortestDelta(from: number, to: number, count: number): number {
  if (count <= 0) return to - from;
  const d = ((to - from) % count + count) % count;
  return d > count / 2 ? d - count : d;
}

/**
 * موضع الطاقة على الصفّ.
 *
 * يُعيد MotionValue يحمل موضعاً **غير ملفوف** (قد يتجاوز عدد العناصر أو
 * ينزل تحت الصفر) — وهذا مقصود: النابض يحتاج مساراً متّصلاً كي ينزلق،
 * ولفّه إلى المدى [0, count) كان سيُحدث قفزة في منتصف السفر. اللفّ يحدث
 * عند القياس في `ringDistance` لا عند التخزين.
 *
 * النابض هو نابض انزلاق الصفّ نفسه: الطاقة والصفّ يتحرّكان ككائن واحد،
 * لا كطبقتين تتصادفان.
 */
export function useEnergyField(target: number, count: number): MotionValue<number> {
  const still = useReducedMotion();
  const unwrapped = useRef(target);
  const pos = useMotionValue(target);

  /*
   * القيادة بـ`animate` صراحةً، لا بـ`useSpring`.
   *
   * جرّبتُ صيغتَي `useSpring` كلتيهما وفشلتا هنا، وكلٌّ منهما بأعراض
   * مختلفة كلّفتني تشخيصين خاطئين:
   *
   *   • `useSpring(motionValue, cfg)` — تتخلّف الذروة خطوةً عن التركيز
   *     دائماً، ثم تتجمّد نهائياً بعد أول التفاف عند طرف الصفّ.
   *   • `useSpring(number, cfg)` — الوسيط نفسه **يقود** النابض، فيتنازعه
   *     مصدران: الوسيط بالموضع الملفوف (0‥8) و`set` بالموضع المتّصل.
   *     تحسّنت النتيجة إلى 7 من 12 ثم تجمّدت ثانيةً.
   *
   * القياس هو ما حسم في كل مرّة: الحساب وحده أعطى المواضع الصحيحة كلّها،
   * وتخطّي النابض جعل الذروة تطابق التركيز في ستّ خطوات متتالية. فبقي
   * المتّهم واحداً ولم يكن حسابي.
   *
   * `animate(value, to, transition)` لا لبس فيه: هدفٌ واحد، ومصدرُ قيادة
   * واحد، وإلغاءٌ صريح للحركة السابقة. وهو أيضاً ما يمنح المقاطعة
   * المطلوبة — يُعيد التوجيه من الموضع والسرعة الحاليّين، فالضغط المتتابع
   * السريع يتدفّق بلا قفز ولا طابور.
   */
  useEffect(() => {
    unwrapped.current += shortestDelta(
      ((unwrapped.current % count) + count) % count,
      target,
      count,
    );
    /* مع تفضيل «تقليل الحركة» لا سفر: الطاقة تصل مباشرةً. التسلسل الهرمي
       يبقى كاملاً (الشدّة نفسها عند الاستقرار)، ويسقط المشهد وحده. */
    if (still) {
      pos.set(unwrapped.current);
      return;
    }
    /*
     * تسليم السرعة **صراحةً** عند إعادة التوجيه.
     *
     * الاستمرارية كانت قائمة على سلوكٍ ضمنيّ: النابض يلتقط سرعة القيمة
     * الحالية إن لم تُمرَّر إليه واحدة. وهذا صحيح في الغالب، لكنّه يعتمد
     * على أن تكون القيمة قد تغيّرت في الإطارين الأخيرين — و`stop()` يسبق
     * الاستدعاء الجديد مباشرةً، فإن وقع التوجيه في إطارٍ لم تُحدَّث فيه
     * القيمة قُرئت السرعة صفراً، فتبدأ الرحلة الجديدة من سكون.
     *
     * والفرق محسوس تحديداً في الحالة التي تهمّ: الضغط المتتابع السريع.
     * صفرُ سرعةٍ عند كل ضغطة يحوّل التدفّق المتّصل إلى سلسلة انطلاقاتٍ
     * قصيرة — أي «إعادة تشغيل» وهو معيار رفضٍ صريح.
     *
     * فتُقرأ السرعة قبل الإيقاف وتُمرَّر يداً بيد. الزخم لا يُفترَض.
     */
    const carried = pos.getVelocity();
    const controls = animate(pos, unwrapped.current, {
      ...spring.navigation,
      velocity: carried,
    });
    return () => controls.stop();
  }, [target, count, pos, still]);

  return pos;
}
