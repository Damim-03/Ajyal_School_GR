import type { Transition, TargetAndTransition } from "motion/react";

import { curve, icon, reduced, settle } from "./tokens";

/**
 * أشكالُ الدخول — تُشتقّ هنا ولا تُكتب في الرئيسية.
 *
 * وصارتا دالّتين لا واحدة، وهذا هو التعديلُ الجوهري: **الشريطُ يدخل
 * كطبقة، والبلاطةُ المركَّزة وحدها لها شأنٌ خاصّ**. كان الاثنان قراراً
 * واحداً موزّعاً على تسع بلاطات، فكانت الأيقوناتُ هي الحدث — والحدثُ
 * يجب أن يكون التركيز.
 */

/*
 * مراجعُ ثابتةٌ على مستوى الوحدة.
 *
 * ليست تحسيناً: `motion` يقارن هدفَ الحركة بالذي قبله ليقرّر إعادةَ
 * التشغيل، ومصفوفةٌ تُبنى في كلّ عرضٍ تصل إليه **جديدةً في كلّ مرّة**.
 * فكانت لقطاتُ المقياس تُستأنف من أوّلها كلّما تغيّرت حالةٌ أخرى في
 * الرئيسية (الساعةُ وحدها تُعيد العرضَ كلَّ ثانية) — أي بلاطةٌ تنبض بلا
 * سبب. البناءُ مرّةً واحدة هنا يقطع ذلك من أصله.
 */
const SETTLE_SCALE = [...settle.scale];
const SETTLE_TIMES = [...settle.times];

/* ============================================================
 * ② حضورُ الشريط — طبقةٌ واحدة
 * ============================================================ */

export interface RailEntrance {
  initial: TargetAndTransition;
  animate: TargetAndTransition;
  transition: Transition;
}

/**
 * **الشريطُ يحضر، ولا يُبنى من قطع.**
 *
 * قناةٌ واحدة (شفافية) على عنصرٍ واحد (الصفّ). لا تتابع، ولا إزاحة، ولا
 * مقياس، ولا تمويه.
 *
 * ولماذا لا مقياسَ ولو ضئيلاً: الصفُّ عرضُه ~950px، ومقياسُ 0.985 يزيح
 * طرفَيه سبعةَ بكسلات. والبلاطةُ المركَّزة يجب أن تقف **داخل إطارها
 * الثابت** في كلّ إطارٍ من المشهد — فأيُّ مقياسٍ على الصفّ يزحزحها عنه
 * ما لم يكن منشؤه عند المرساة بالضبط، وهو موضعٌ يتغيّر مع التركيز. سبعةُ
 * بكسلاتٍ من الانحراف تكلّف أكثر ممّا تشتريه حركةٌ لا تكاد تُرى.
 *
 * والشفافيةُ لا تبدأ من الصفر: 0.7 تُبقي الشريطَ مقروءاً بنيةً منذ
 * الإطار الأوّل — يعرف المستخدمُ أنّ هناك تسعةَ أقسام قبل أن يعرف أيَّها
 * المحدَّد.
 */
export function railEntrance(present: boolean, still: boolean): RailEntrance {
  return {
    initial: { opacity: icon.rail.from },
    animate: { opacity: present ? icon.rail.to : icon.rail.from },
    transition: {
      duration: still ? reduced.duration : icon.rail.duration,
      ease: curve.enter,
    },
  };
}

/* ============================================================
 * ⑥ تأكيدُ العنصر — البلاطة المركَّزة وحدها
 * ============================================================ */

export interface TileEntranceInput {
  index: number;
  /** البلاطةُ التي يستقرّ عليها الانتباه. */
  focused: number;
  /** بلغ الجدولُ مرحلةَ تأكيد العنصر. */
  confirmed: boolean;
  /** الشفافيةُ المطلوبة عند السكون (‏1، أو خفوتُ الجيران عند الامتداد). */
  restOpacity: number;
  still: boolean;
}

export interface TileEntrance {
  animate: TargetAndTransition;
  transition: Transition;
}

/**
 * **البلاطة — لا دخولَ لها، إلّا المركَّزة عند لحظة تأكيدها.**
 *
 * ما كان: تسعُ بلاطاتٍ لكلٍّ منها شفافيةٌ وتأخيرٌ خاصّان. وما صار: لا
 * شيء — الشفافيةُ صعدت إلى الصفّ، والوزنُ البصريّ (الحجم والسطوع
 * والتشبّع) يملكه حقلُ الطاقة وهو قائمٌ منذ الإطار الأوّل.
 *
 * فلم يبقَ هنا إلّا شأنٌ واحد: عند المرحلة ⑥ تُقرّ البلاطةُ المركَّزة
 * نفسَها بلقطات مقياس 0.965 ← 0.998 ← 1. وهو تحويلٌ حول مركزها فلا يمسّ
 * التخطيط ولا يزحزح جيرانها ولا يخرجها عن إطارها الثابت.
 *
 * والتجاوزُ صفرٌ عمداً — «‏No bounce. No elastic motion.‏» والوصولُ ليس
 * إفلاتاً.
 *
 * و`restOpacity` تبقى هنا لأنّها ليست دخولاً: هي خفوتُ الجيران حين تمتدّ
 * الصفحةُ على قسمٍ ما، وتلك حالةٌ تفاعليةٌ تعيش بعد انتهاء المشهد كلِّه.
 */
export function tileEntrance({
  index, focused, confirmed, restOpacity, still,
}: TileEntranceInput): TileEntrance {
  const confirming = index === focused && confirmed && !still;

  return {
    animate: { opacity: restOpacity, scale: confirming ? SETTLE_SCALE : 1 },
    transition: {
      duration: still ? reduced.duration : settle.duration,
      ease: curve.enter,
      /*
       * **اللقطاتُ تخصّ المقياسَ وحده — ولا يجوز أن تُكتب في جذر
       * الانتقال.**
       *
       * كُتبت هناك أوّلاً، فقِستُ النتيجة على البلاطة المركَّزة فوجدتها
       * تنطفئ في منتصف دخولها ثمّ تقفز إلى 1. والسببُ أنّ `times` في
       * الجذر يسري على **كلّ** خاصّية متحرّكة: فورثته الشفافيةُ ولها
       * محطّتان لا ثلاث، ومن هذا التنافر وُلد الانحدارُ العكسي.
       */
      ...(confirming
        ? { scale: { duration: settle.duration, ease: curve.settle, times: SETTLE_TIMES } }
        : {}),
    },
  };
}
