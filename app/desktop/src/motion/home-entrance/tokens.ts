export type EntranceProfile = "auth" | "cold" | "return";

/** الطليعة: ما يجري قبل أن توجد الرئيسية. للإقلاع البارد لا طليعةَ له. */
export const leadOf = (profile: EntranceProfile): Mark[] =>
  profile === "auth" ? AUTH_LEAD : [];

/** التجميع: ما يجري بعد أن تصير الرئيسيةُ مرسومة. */
export const assemblyOf = (profile: EntranceProfile): Mark[] =>
  profile === "auth" ? HOME_MARKS : profile === "cold" ? COLD_MARKS : [];

