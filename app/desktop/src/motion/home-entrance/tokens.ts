/**
 * نظام دخول الرئيسية — الأرقام وحدها.
 *
 * ما كان: رحلةُ «كلمة المرور ← الرئيسية» يملكها ثلاثةُ مواضع لا يعرف
 * أحدُها الآخر. شاشةُ الاختيار تنتظر 1350ms بمؤقّتٍ مكتوبٍ فيها، و`App`
 * يبدّل الشجرةَ تبديلاً حادّاً، والرئيسيةُ تبدأ جدولَ إقلاعها من الصفر
 * (‏1240ms أخرى). المجموع نحو **2.6 ثانية**، وبينهما إطارٌ لا يملكه أحد:
 * لوحةُ البيئة تُدمَّر مع تفكيك شاشة الإقلاع قبل أن تُرسم الرئيسية.
 *
 * ما صار: جدولٌ واحد يملكه `controller.ts`، ومراحلُه **متراكبة** لا
 * متعاقبة — الرئيسيةُ تُركَّب وتبدأ استيقاظها بينما شاشةُ كلمة المرور ما
 * زالت تنسحب فوقها. المجموع ~950ms، بلا إطارٍ أسود.
 *
 * الأرقام هنا مضبوطةٌ بالمشاهدة، ولا تُكتب في أي مكوّن.
 */

/* ============================================================
 * 1 — الخطوات
 * ============================================================ */

/**
 * الخطوة عدّادٌ يتقدّم ولا يرجع. سبب كونه رقماً لا سلسلةً: كلّ مستهلك
 * يسأل «هل بلغنا كذا؟» بمقارنةٍ واحدة (`step >= STEP.focus`) بدل جدول
 * أسبقيّاتٍ يُكتب في كلّ موضع.
 *
 * وهي مطابقةٌ بنيوياً لـ`STAGE` في spatial/boot.ts — الرئيسية تقرأ
 * أعلامَها كما كانت، ولم يتبدّل إلّا **من** يحرّكها.
 */
export const STEP = {
  /** لم يبدأ شيء. */
  dark: 0,
  /** واجهةُ المصادقة بدأت تنسحب. */
  authExit: 1,
  /** البيئةُ تتحوّل — لا تنطفئ. */
  environment: 2,
  /** غلافُ الرئيسية يظهر: الجوّ والخلفية والشريط العلوي. */
  shell: 3,
  /** بلاطاتُ التنقّل تدخل بتتابعها. */
  navigation: 4,
  /** الطاقةُ تصل إلى البلاطة المركَّزة. */
  focus: 5,
  /** الحافّة تُعرَّف — حلقةُ التركيز آخر ما يُرسم. */
  edge: 6,
  /** البطلُ والسياق. */
  content: 7,
  /** استقرّ كلُّ شيء — الحالةُ التفاعلية الطبيعية. */
  complete: 8,
} as const;

export type Step = (typeof STEP)[keyof typeof STEP];

/** المرحلة الدلالية — ما يُقرأ في الشيفرة وفي لوحة التنقيح. */
export type HomeEntrancePhase =
  | "idle"
  | "auth-exit"
  | "environment-transition"
  | "shell-emerge"
  | "navigation-enter"
  | "focus-settle"
  | "content-enter"
  | "complete";

/** الخطوة ← المرحلة. الحافّة ليست مرحلةً بذاتها: هي ذيلُ التركيز. */
export const phaseOfStep = (step: number): HomeEntrancePhase =>
  step >= STEP.complete
    ? "complete"
    : step >= STEP.content
      ? "content-enter"
      : step >= STEP.focus
        ? "focus-settle"
        : step >= STEP.navigation
          ? "navigation-enter"
          : step >= STEP.shell
            ? "shell-emerge"
            : step >= STEP.environment
              ? "environment-transition"
              : step >= STEP.authExit
                ? "auth-exit"
                : "idle";

