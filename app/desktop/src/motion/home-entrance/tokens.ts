export interface Mark {
  /** بالمللي ثانية من بدء الجدول. */
  at: number;
  step: Step;
}

/**
 * ① الطليعة — من نجاح المصادقة إلى تركيب الرئيسية.
 *
 * الصفر هو لحظةُ نجاح `POST /auth/login`، لا لحظةُ ضغط Enter: كلُّ ما
 * قبله انتظارُ شبكةٍ لا يملك أحدٌ مدّته، وبناءُ مشهدٍ على زمنٍ مجهول
 * يجعل نصفَ الرحلات تبدو بطيئةً ونصفَها مقطوعاً.
 *
 * علامتان فقط، والفجوةُ بينهما مقصودة — انظر `handoff.mount`.
 */
const AUTH_LEAD: Mark[] = [{ at: 0, step: STEP.authExit }];

/**
 * ② تجميعُ الرئيسية — **مُسنَدٌ إلى أوّل إطارٍ بعد تركيبها، لا إلى
 * نجاح المصادقة**.
 *
 * وهذا أهمُّ قرارٍ في الجدول كلّه، وسببُه قياسٌ لا ذوق.
 *
 * كانت هذه العلاماتُ مطلقةً من لحظة المصادقة (‏200، 300، 470…). فقِستُ
 * بناءَ الإنتاج فوجدتُ تركيبَ الرئيسية يحجب الخيطَ الرئيسي **310ms**
 * دفعةً واحدة: تسعُ بلاطاتٍ بطبقاتها، وطبقاتُ الخلفية، ولوحةُ الجوّ.
 * فكانت ثلاثُ مراحلَ متتالية (الغلاف والتنقّل والتركيز) تُستهلك في
 * التقّة الواحدة التي تلي الحجب — أي أنّ المستخدم يرى الانسحابَ يتجمّد،
 * ثمّ يظهر الصفُّ والتركيزُ معاً بلا تتابع. التتابعُ الذي بُني هذا
 * النظام كلُّه لأجله كان يضيع في أسوأ لحظة.
 *
 * ولا يُعالَج بتأخيرٍ ثابت: مدّةُ التركيب تتبع الجهاز وعددَ الأقسام،
 * وأيُّ رقمٍ نكتبه يكون كبيراً على جهازٍ وصغيراً على آخر.
 *
 * فصار المشهدُ يُسنَد إلى الحدث لا إلى الساعة: الرئيسيةُ تُعلن
 * `ready()` في أوّل إطارٍ بعد رسمها، ومن هناك يبدأ التجميع. الحجبُ يقع
 * **قبل** ذلك، خلف شاشةٍ ما زالت معتمة، فلا يُرى منه شيء.
 */
