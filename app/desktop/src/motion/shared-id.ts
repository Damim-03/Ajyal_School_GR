/**
 * هويّات العناصر المشتركة (§27/§28).
 *
 * العنصر المشترك هو الذي **يستمرّ** بين حالتين بدل أن يختفي هنا ويظهر
 * هناك: أيقونة البلاطة تصير أيقونة البطل، وعنوان القسم يصير عنوان الشاشة.
 * محرّك الحركة يستطيع جسر الحالتين، لكنه يحتاج أن يعرف أنّهما **الشيء
 * نفسه** — وهذه معرفة لا يمكن استنتاجها من الشجرة.
 *
 * لماذا مولّد لا سلاسل مكتوبة؟ لأن سلسلة مكتوبة يدوياً في موضعين تفشل
 * بصمت عند أول اختلاف حرف: لا خطأ، لا تحذير، فقط عنصر يومض بدل أن ينتقل.
 * وقد وقع هذا فعلاً في المشروع — `layoutId` مكتوب حرفياً جسر شريحة
 * الترويسة بأفاتار شاشة الدخول فظهر بقطر ~95px خارج مكانه ثم اختفى.
 *
 * قاعدة الأمان الملازمة: هويّة مشتركة يجب أن تكون **فريدة في اللحظة
 * الواحدة**. عنصران يحملان الهوية نفسها في الشاشة نفسها يجعلان المحرّك
 * يحاول تحريك أحدهما إلى الآخر.
 *
 * تُبنى البنية الآن ويُستهلك الجسر في فصل لاحق (§76) — ما يُستعمل منها
 * اليوم هو إطار التركيز المشترك.
 */

/** أجزاء العنصر التي قد تستمرّ بين الحالات. */
export type SharedPart = "artwork" | "title" | "hero" | "accent" | "action";

/** هويّة القسم نفسه: `module:sales`. */
export const moduleId = (id: string) => `module:${id}`;

/** هويّة جزء منه: `module:sales:artwork`. */
export const sharedId = (id: string, part: SharedPart) => `module:${id}:${part}`;

