/** خطوة واحدة في الصفّ، تلتفّ عند الطرفين. */
export function stepFocus(step: Step, source: InteractionSource) {
  const { focus, count, dispatch } = useMotionStore.getState();
  if (count <= 0) return;
  dispatch({ type: "FOCUS_CHANGE", to: focus.id + step, source });
}
