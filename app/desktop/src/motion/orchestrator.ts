import { create } from "zustand";
import type { Transition } from "motion/react";
import type { Step } from "./direction";

/**
 * منسّق الحركة — قلب الفصل الأول (§11 → §25).
 *
 * التحوّل المعماري الذي يصنعه:
 *
 *   قبل: كل مكوّن يملك حركته. الرئيسية تحمل سبع حالات منفصلة
 *        (focused, navDir, launching, chromeReady, bgReady, entered,
 *        settling) وكل طبقة تقرّر بنفسها متى تتحرّك. لا أحد يعرف ما الذي
 *        يجري الآن، فلا يمكن منع التصادم ولا مقاطعة ما يجب مقاطعته.
 *
 *   بعد: **حدث تفاعل واحد** يدخل هنا، فتُشتقّ منه حالة واحدة تقرأها كل
 *        الطبقات. البلاطة والعنوان والخلفية والبطاقات لا تقرّر شيئاً —
 *        تستجيب لحالة مشتركة.
 *
 * لماذا مخزن (zustand) لا Context؟ ثلاثة أسباب عملية:
 *   • لوحة التنقيح تُركَّب في Providers أي خارج شجرة الرئيسية؛ مع Context
 *     كانت ستحتاج مزوّداً يلفّ التطبيق كلّه فيُعيد عرضه عند كل تنقّل.
 *   • المخزن يبقى بعد تفكيك الرئيسية، فهو نفسه **الذاكرة المكانية**:
 *     العودة من قسم تجدك حيث كنت (§72) بلا متغيّر عام منفصل.
 *   • بقية التطبيق تستعمل zustand أصلاً (auth، notify، environment) —
 *     لا نمط جديد يُتعلَّم.
 *
 * ما ليس هنا عمداً: أي قيمة تتغيّر كل إطار. الانجراف والتكبير يعيشان في
 * MotionValue داخل CameraProvider خارج شجرة React (§39). هنا **حالة
 * دلالية** فقط: بضعة تغيّرات في الثانية على الأكثر.
 */

/* ============================================================
 * 1 — مصدر التفاعل (§18)
 * ============================================================ */

/**
 * من أين جاء التركيز. ليس ترفاً تشخيصياً: التنقّل بلوحة المفاتيح مقصود
 * ومتتابع، وبالفأرة استكشافي ومتقطّع — والسلوك قد يختلف بينهما (مثلاً
 * دفعة الكاميرا تُناسب الخطوة المقصودة لا مرور المؤشّر العابر).
 */
export type InteractionSource = "keyboard" | "pointer" | "wheel" | "programmatic" | "restored";

/* ============================================================
 * 2 — آلة حالات الحركة (§13)
 * ============================================================ */

/**
 * الحالات الصريحة. وجودها هو ما يجعل منع التصادم ممكناً أصلاً: بلا حالة
 * معلنة لا يستطيع النظام أن يعرف ما الذي يجب أن يقاطع وما الذي يجب أن
 * يُرفض.
 *
 * (المواصفة تذكر FOCUSING وNAVIGATING منفصلتين؛ دُمجتا هنا عن قصد —
 *  في هذه الواجهة لا يوجد تركيز بلا تنقّل، وحالة لا تفرّق شيئاً هي
 *  تجريد بلا مشكلة يحلّها §61.)
 */
export type MotionPhase =
  /** الغلاف يتركّب لأول مرّة — مقدّمة الدخول تعمل. */
  | "ENTERING"
  /** مستقرّ، لا شيء يتحرّك. البيئة وحدها حيّة. */
  | "IDLE"
  /** المؤشّر يتجوّل فوق البلاطات — اهتمام بلا قرار (EXPLORE). */
  | "EXPLORE"
  /** الانتباه ينتقل والطبقات تستجيب (FOCUS). */
  | "NAVIGATING"
  /** الانتباه استقرّ والمعاينة السياقية معروضة (PREVIEW). */
  | "PREVIEWING"
  /**
   * المستخدم أكّد المعاينة، فانفتحت **منطقة السياق** داخل الرئيسية نفسها
   * (ACTIVE + EXPANDED).
   *
   * دُمجت مرحلتا «التأكيد» و«التوسّع» في حالة واحدة عن قصد: لا يوجد بينهما
   * لحظةٌ يستطيع المستخدم أن يعيش فيها — التأكيد يُطلق التوسّع فوراً.
   * وحالةٌ لا يمكن ملاحظتها ولا الوقوف عندها تجريدٌ بلا مشكلة يحلّها.
   *
   * ما يميّزها عمّا قبلها: التنقّل يصير **رأسياً داخل السياق** لا أفقياً
   * بين الأقسام، والرئيسية تمتدّ إلى أسفل بدل أن تُستبدل.
   */
  | "PREVIEW_ACTIVE"
  /** لحظة الالتزام: السفر إلى داخل القسم (ENTER). */
  | "EXITING"
  /** المستخدم داخل القسم — الرئيسية لم تختفِ، هو الذي غاص أعمق. */
  | "WORKSPACE"
  /** رحلة العودة جارية (RETURN). */
  | "RETURNING";

/**
 * خريطة الأسماء إلى مفردات هذا الفصل. أُبقيت الأسماء الأصلية عمداً — هي
 * موثَّقة ومختبَرة ومستهلَكة في أماكن عدّة، وإعادة تسميتها تغييرٌ بلا
 * مكسب. الدلالة هي المهمّة، وهذه هي:
 *
 *   IDLE      → IDLE          لا شيء يملك الانتباه
 *   EXPLORE   → EXPLORE       اهتمام بالمؤشّر، بلا قرار
 *   FOCUS     → NAVIGATING    الانتباه يسافر
 *   PREVIEW   → PREVIEWING    الوجهة شرحت نفسها
 *   ACTIVE    → PREVIEW_ACTIVE‏ الالتزام مُصوَّب
 *   ENTER     → EXITING       السفر إلى الداخل
 *   WORKSPACE → WORKSPACE     وصلنا
 *   RETURN    → RETURNING     السفر إلى الخارج
 *
 * الفارق الجوهري الذي تحرسه هذه القائمة: **الاختيار ليس تنقّلاً**.
 * EXPLORE اهتمام، وNAVIGATING انتباه، وEXITING وحدها قرار.
 */

/* ============================================================
 * 3 — التركيز كحالة من الدرجة الأولى (§17)
 * ============================================================ */

export interface FocusState {
  /** العنصر المركَّز الآن. */
  id: number;
  /** الذي غادرناه — تحتاجه الطبقات التي تُخرِج القديم وتُدخل الجديد. */
  previousId: number | null;
  /** ‎+1 تقدّم، ‎-1 رجوع، 0 لا حركة. دلالي لا بصري. */
  direction: number;
  /** كم عنصراً قُطع في هذه القفزة (النقر البعيد يقفز أكثر من سهم). */
  distance: number;
  /** خطوات في الثانية — يقيس مدى اندفاع المستخدم. */
  velocity: number;
  /** لحظة آخر تنقّل (performance.now). */
  timestamp: number;
  source: InteractionSource;
}

/* ============================================================
 * 4 — الأحداث الدلالية (§12)
 * ============================================================ */

/**
 * المفردات التي تتكلّم بها الواجهة. لاحظ أنّ أياً منها لا يذكر شفافية ولا
 * إزاحة ولا مدّة: الحدث يقول **ماذا حدث**، والحالة الناتجة تقرّر الشكل.
 * هذا هو الفصل الذي يسمح بتبديل الشكل لاحقاً بلا لمس المنطق.
 */
export type MotionEvent =
  | { type: "SHELL_READY" }
  /** المؤشّر دخل/غادر بلاطة — اهتمام لا قرار. */
  | { type: "EXPLORE"; index: number | null }
  | { type: "FOCUS_CHANGE"; to: number; source: InteractionSource }
  /** تأكيد المعاينة ⇒ انفتاح منطقة السياق داخل الرئيسية. */
  | { type: "FOCUS_CONFIRM" }
  /** طيّ منطقة السياق والعودة إلى التصفّح الأفقي. */
  | { type: "COLLAPSE" }
  | { type: "CONTEXT_SETTLED" }
  /** لحظة الالتزام — الوحيدة التي تُغيّر المكان. */
  | { type: "MODULE_ENTER"; module: string }
  /** وصلنا إلى القسم فعلاً (رُكِّبت شاشته). */
  | { type: "WORKSPACE_READY"; module: string }
  /** بدأت رحلة العودة — قبل تغيّر المسار بلحظة. */
  | { type: "RETURN_START" }
  | { type: "MODULE_EXIT" }
  | { type: "RESET" };

/* ============================================================
 * 5 — التوقيت
 * ============================================================ */

/**
 * متى تُعتبر الاستجابة مكتملة فننتقل NAVIGATING → PREVIEWING.
 * 720ms = نهاية أبطأ طبقة (الخلفية: 60ms تأخير + 660ms مدّة). المعنى:
 * الحالة لا تُعلن الاستقرار قبل أن تستقرّ آخر طبقة فعلاً.
 */
export const SETTLE_MS = 720;

/** سقف السرعة المحسوبة — يمنع أن تُنتج قفزةٌ فوريةٌ رقماً بلا معنى. */
const MAX_VELOCITY = 24;

/* ============================================================
 * 6 — المخزن
 * ============================================================ */

interface MotionStore {
  phase: MotionPhase;
  focus: FocusState;
  /** القسم الذي دخلناه (أو الذي نغادر إليه). */
  activeModule: string | null;
  previousModule: string | null;
  /**
   * الحالة الثالثة (§19/§20): المؤشّر يستكشف هذا العنصر.
   *
   * HOVERED ≠ FOCUSED ≠ ACTIVE. التحويم **اهتمام** عابر، والتركيز **موضع
   * التنقّل الحالي**، والمؤكَّد **السياق المعروض**. خلطها هو ما يجعل تمرير
   * الفأرة عبر الشريط يبدّل الخلفية والعنوان عشر مرّات في ثانية.
   *
   * لذلك تُخزَّن ولا تُغذّي التنقّل: تصف الاهتمام ليقرأه ما يحتاجه.
   */
  hovered: number | null;
  /** عدد العناصر في الصفّ — يُسجَّل كي يلتفّ التنقّل عند الطرفين. */
  count: number;
  /** مضاعف سرعة للتطوير فقط (§58). 1 في الإنتاج دائماً. */
  speed: number;

  dispatch: (e: MotionEvent) => void;
  setCount: (n: number) => void;
  setHovered: (i: number | null) => void;
  setSpeed: (v: number) => void;
}

const initialFocus: FocusState = {
  id: 0, previousId: null, direction: 0, distance: 0,
  velocity: 0, timestamp: 0, source: "restored",
};

/** مؤقّت الاستقرار — واحد فقط، يُلغى ويُعاد جدولته عند كل تنقّل. */
let settleTimer = 0;

export const useMotionStore = create<MotionStore>()((set, get) => ({
  phase: "ENTERING",
  focus: initialFocus,
  activeModule: null,
  previousModule: null,
  hovered: null,
  count: 0,
  speed: 1,

  setCount: (n) => set((s) => (s.count === n ? s : { count: n })),
  setHovered: (i) => set((s) => (s.hovered === i ? s : { hovered: i })),
  setSpeed: (v) => set({ speed: v }),

  dispatch: (e) => {
    const s = get();

    switch (e.type) {
      case "SHELL_READY":
        // العودة من قسم تركّب الغلاف وهو جاهز أصلاً؛ لا تُرجِع حالة مغادِرة.
        return set(s.phase === "ENTERING" ? { phase: "PREVIEWING" } : {});

      /*
       * الاستكشاف حالة قائمة بذاتها، لا مقدّمةَ تركيز.
       *
       * هذا هو الفرق الذي يحرسه الفصل كلّه: المؤشّر يمرّ فوق بلاطة فيقول
       * «ما هذه؟» — وهذا **اهتمام**. الانتباه لا ينتقل، والمعاينة لا
       * تتبدّل، والخلفية لا تتحرّك. لو حرّكها التحويم لتبدّل العالم كلّه
       * عشر مرّات وأنت تمدّ يدك نحو زرّ.
       *
       * ولذلك لا تدخل EXPLORE إلا من سكونٍ أو معاينة مستقرّة: أثناء سفر
       * الانتباه أو المغادرة، مرورُ المؤشّر لا يعني شيئاً ويجب ألّا يسجَّل.
       */
      case "EXPLORE": {
        const idle = s.phase === "IDLE" || s.phase === "PREVIEWING" || s.phase === "EXPLORE";
        if (!idle) return set({ hovered: e.index });
        if (e.index === null)
          return set({ hovered: null, phase: s.phase === "EXPLORE" ? "PREVIEWING" : s.phase });
        return set({ hovered: e.index, phase: "EXPLORE" });
      }

      case "FOCUS_CHANGE": {
        /*
         * منع التصادم: انتباه الرئيسية لا يتحرّك إلا والمستخدم **فيها**.
         *
         * كان الحارس يمنع EXITING وحدها، فكشف الاختبار ثغرتين:
         *   • أثناء المغادرة — الضغط على سهم والحجاب يتمدّد كان يبدّل
         *     خلفية القسم تحته، فيصل المستخدم إلى المبيعات وقد ومض لون
         *     المخزون في طريقه. (عولجت في الفصل الأول.)
         *   • داخل مساحة العمل — سهمٌ في شاشة المخزون كان يحرّك تركيز
         *     الرئيسية من بعيد ويسحب الحالة من WORKSPACE إلى NAVIGATING،
         *     فتجد عند رجوعك أنّك واقف على قسم لم تختره.
         *
         * الحارس الآن يذكر الحالات التي يجوز فيها التنقّل، لا التي لا
         * يجوز: القائمة السالبة تُنسى عند إضافة حالة، والموجبة لا تُنسى.
         */
        const inHome =
          s.phase === "IDLE" || s.phase === "EXPLORE" ||
          s.phase === "NAVIGATING" || s.phase === "PREVIEWING" ||
          s.phase === "PREVIEW_ACTIVE" || s.phase === "ENTERING";
        if (!inHome) return;

        const n = s.count > 0 ? ((e.to % s.count) + s.count) % s.count : e.to;
        if (n === s.focus.id) return;

        const now = performance.now();
        const dt = s.focus.timestamp ? (now - s.focus.timestamp) / 1000 : 0;
        /*
         * السرعة تُقاس من الفارق الزمني بين تنقّلين متتاليين لا من محرّك
         * الحركة: الضغط المتتابع السريع يرفعها، والتنقّل المتمهّل يُبقيها
         * قرب الصفر. أول تنقّل في الجلسة سرعته صفر — لا سابق يُقاس عليه.
         */
        const velocity = dt > 0 ? Math.min(MAX_VELOCITY, 1 / dt) : 0;

        /* الالتفاف عند الطرفين يجعل الفارق العددي مضلِّلاً: من الأخير إلى
           الأول خطوة واحدة لا ثماني. نأخذ الأقصر على الحلقة. */
        const raw = Math.abs(n - s.focus.id);
        const distance = s.count > 0 ? Math.min(raw, s.count - raw) : raw;

        /*
         * إعادة التوجيه لا الاصطفاف (§15): لا طابور ولا كبح زمني. الضغط
         * الرابع يكتب فوق الثالث، والنوابض في الطبقات تُعيد توجيه نفسها من
         * موضعها وسرعتها الحاليّين. أربع ضغطات سريعة = انتقال واحد متصل.
         */
        window.clearTimeout(settleTimer);
        settleTimer = window.setTimeout(
          () => get().dispatch({ type: "CONTEXT_SETTLED" }),
          SETTLE_MS / (get().speed || 1),
        );

        return set({
          phase: "NAVIGATING",
          /* الانتباه تحرّك ⇒ الاهتمام العابر انتهى؛ حالتان لا تتعايشان. */
          hovered: null,
          focus: {
            id: n,
            previousId: s.focus.id,
            direction: n > s.focus.id ? 1 : -1,
            distance,
            velocity,
            timestamp: now,
            source: e.source,
          },
        });
      }

      case "CONTEXT_SETTLED":
        // لا تُرقّ حالةً غادرت التنقّل أصلاً (مغادرة أو تأكيد سبقا المؤقّت).
        return set(s.phase === "NAVIGATING" ? { phase: "PREVIEWING" } : {});

      case "FOCUS_CONFIRM":
        /* التأكيد لا يُغادر المكان — يفتح ما تحته. ولا يُقبل إلا من معاينة
           مستقرّة أو استكشاف: أثناء سفر الانتباه لم يستقرّ شيءٌ ليُؤكَّد. */
        return set(
          s.phase === "PREVIEWING" || s.phase === "EXPLORE" || s.phase === "NAVIGATING"
            ? { phase: "PREVIEW_ACTIVE", hovered: null }
            : {},
        );

      case "COLLAPSE":
        return set(s.phase === "PREVIEW_ACTIVE" ? { phase: "PREVIEWING" } : {});

      case "MODULE_ENTER":
        window.clearTimeout(settleTimer);
        return set({
          phase: "EXITING",
          previousModule: s.activeModule,
          activeModule: e.module,
        });

      /*
       * وصلنا. الرئيسية **لم تُغلَق** — المستخدم غاص أعمق داخل العالم
       * نفسه، ولهذا يبقى `activeModule` مضبوطاً: البيئة تقرؤه فتُبقي
       * خلفية القسم ولونه حاضرَين في مساحة العمل، فتكون الشاشة الجديدة
       * **استمراراً للمعاينة** لا بديلاً عنها.
       */
      case "WORKSPACE_READY":
        window.clearTimeout(settleTimer);
        return set({ phase: "WORKSPACE", activeModule: e.module });

      /* رحلة العودة تبدأ قبل تغيّر المسار، فيملك الحجابُ لونَ القسم الذي
         نغادره لا لوناً عاماً. */
      case "RETURN_START":
        return set(s.phase === "RETURNING" ? {} : { phase: "RETURNING" });

      /*
       * «نحن في الرئيسية الآن» — حدث **مصالحة** لا مجرّد انتقال.
       *
       * يُرسَل من أثر تركيب الرئيسية دائماً، أياً كانت الحالة السابقة. وهذا
       * الإطلاق غير المشروط ثمنُ عطلٍ حقيقي وقعتُ فيه: كان يُرسَل فقط حين
       * `!isFirstIntro` — أي مربوطاً بعلامةٍ مهمّتها الصوت والمقدّمة، لا
       * التنقّل. فحين أُعيد تحميل الصفحة أثناء وجود المستخدم في قسم، عادت
       * تلك العلامة إلى قيمتها الأولى بينما بقيت الحالة `RETURNING`، ولم
       * يبقَ في النظام ما يُخرجها منها. النتيجة: الأسهم لا تعمل إطلاقاً —
       * لأن التنقّل مرفوض في كل حالة ليست حالةَ رئيسية.
       *
       * الدرس: الحالة التي يُدخَل إليها من عدّة طرق يجب أن تُصالَح من مكان
       * واحد لا مشروط، لا أن يُخمَّن كلُّ طريق على حدة.
       *
       * وهو عديم الأثر عند التكرار: يُستدعى من أثر تركيب، وReact في وضع
       * Strict يستدعي الأثر مرّتين. لولا ذلك لسجّلت النسخة الأولى «جئنا من
       * المخزون» ومحتها الثانية — وهو خلل ظهر فعلاً في لوحة التنقيح.
       */
      case "MODULE_EXIT": {
        /* المقدّمة الأولى تملك حالتها: لا تُقطع ENTERING من هنا. */
        const phase: MotionPhase = s.phase === "ENTERING" ? "ENTERING" : "PREVIEWING";
        if (s.activeModule === null) return set(s.phase === phase ? {} : { phase });
        return set({ phase, previousModule: s.activeModule, activeModule: null });
      }

      case "RESET":
        // تسجيل الخروج: جلسة جديدة لا ترث موضع الجلسة السابقة.
        window.clearTimeout(settleTimer);
        return set({
          phase: "ENTERING", focus: initialFocus, hovered: null,
          activeModule: null, previousModule: null,
        });
    }
  },
}));

/* ============================================================
 * 7 — واجهات القراءة
 * ============================================================ */

/** الحالة الحالية — تشترك فيها كل الطبقات (§25: مصدر واحد للحقيقة). */
export const useMotionPhase = () => useMotionStore((s) => s.phase);
export const useFocusState = () => useMotionStore((s) => s.focus);

/**
 * عتبة «المستخدم مستعجل»: أكثر من ثلاث خطوات في الثانية.
 * تنقّل متمهّل يبقى دونها؛ الضغط المتتابع على السهم يتجاوزها فوراً.
 */
export const RUSH_VELOCITY = 3;

/**
 * هل يندفع المستخدم عبر الصفّ الآن؟ (§36/§44)
 *
 * هذه ليست إحصاءً — هي **مفتاح الأولوية**. حين يضغط الكاشير السهم ثماني
 * مرّات في الثانية فهو لا ينظر إلى تلاشي البطاقات ولا إلى زجاجها؛ هو ذاهب
 * إلى مكان. والزخرفة في تلك اللحظة لا تُضيف شيئاً بل تسرق وقت الإطار من
 * الشيء الوحيد الذي ينظر إليه: انتقال التركيز.
 *
 * قِسته على الشاشة الحقيقية: أثناء التنقّل المتواصل تتراكم مجموعات بطاقات
 * خارجة لم تُفكَّك بعد — عشرون بطاقة في الإطار الواحد بدل ثلاث — لأن مدّة
 * الخروج (140ms) أطول من الفاصل بين ضغطتين. فتبدأ حلقة تغذية راجعة:
 * إطارات أبطأ ⇒ خروجٌ يطول ⇒ تراكم أكثر ⇒ إطارات أبطأ.
 *
 * فتُقطع الحلقة من جذرها: عند الاندفاع تُسقَط الزخرفة، لا الاستجابة.
 * هذا نصّ §44 حرفياً: تُخفَّض جودة البيئة أوّلاً، لا جودة التفاعل.
 */
export const useRushing = () =>
  useMotionStore((s) => s.phase === "NAVIGATING" && s.focus.velocity > RUSH_VELOCITY);

/** إرسال حدث من أي مكان، بما فيه شيفرة غير React (المؤقّتات والمستمعات). */
export const motionDispatch = (e: MotionEvent) => useMotionStore.getState().dispatch(e);

/**
 * مضاعف سرعة الحركة — أداة تطوير (§58/§59).
 * في الإنتاج يطوي Vite `import.meta.env.DEV` إلى false فيصير المُحدِّد
 * ثابتاً يُعيد 1 دائماً: لا اشتراك، ولا إعادة عرض، ولا كلفة.
 */
export const useMotionSpeed = () =>
  useMotionStore((s) => (import.meta.env.DEV ? s.speed : 1));

/**
 * يبطّئ انتقالاً بمضاعف السرعة، **مع الحفاظ على شخصيته**.
 *
 * النوابض لا تُبطَّأ بإضافة مدّة — لا مدّة فيها أصلاً. تُبطَّأ بخفض
 * الصلابة، لكن الصلابة وحدها لا تكفي: نسبة التخميد ζ = c ÷ 2√(k·m)، فلو
 * ضُربت k بـ s² وحدها لصارت ζ' = ζ ÷ s. عند 0.5× يعني ذلك 0.95 ← 1.89،
 * أي نابض مفرط التخميد: يصل بلا تجاوز ونهايته تبدو «متوقّفة».
 *
 * وهذا أسوأ ما يمكن أن تفعله أداة فحص — تغيّر الشيء الذي جئت تفحصه. وقعتُ
 * فيه فعلاً وكشفه القياس. الحلّ أن يُضرب التخميد بـ s أيضاً، فيُختصر s من
 * البسط والمقام وتبقى ζ كما هي بالضبط.
 */
export function scaleTransition(t: Transition, speed: number): Transition {
  if (speed === 1) return t;
  const out: Record<string, unknown> = { ...t };
  if (typeof out.duration === "number") out.duration = out.duration / speed;
  if (typeof out.delay === "number") out.delay = out.delay / speed;
  if (out.type === "spring") {
    if (typeof out.stiffness === "number") out.stiffness = out.stiffness * speed * speed;
    if (typeof out.damping === "number") out.damping = out.damping * speed;
  }
  return out as Transition;
}

