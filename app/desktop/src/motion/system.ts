/**
 * منحنى النظام كسلسلة CSS.
 *
 * ليس كل ما يتحرّك في التطبيق يمرّ بـmotion: هناك انتقالات CSS خام
 * (‏الدرج الجانبي، حجاب العودة، إضاءة الجولة الإرشادية) كُتبت منحنياتها
 * حرفيّاً. والقيم كانت مطابقة للنظام صدفةً لا اشتقاقاً — فأيّ ضبطٍ
 * للشخصية الحركية كان سيصلح المتحرّك بـmotion ويترك البقيّة على حالها،
 * وهو أوّل طريق إلى لغتين حركيتين في تطبيق واحد.
 *
 * هذه الدالّة تجعل مستهلكي CSS يشتقّون من المصدر نفسه.
 */
export const cssEase = (name: keyof typeof easing) => `cubic-bezier(${easing[name].join(",")})`;

