/**
 * MOTION — المصدر الوحيد لشخصية الحركة في التطبيق كلّه.
 *
 * كان في المشروع نظاما رموز منفصلان لا يعرف أحدهما الآخر:
 *   • motion/tokens.ts        (مدد ومنحنيات عامّة)
 *   • motion/spatial/tokens.ts (نوابض تنقّل الرئيسية، مضبوطة بالقياس)
 * فكانت نافذة الحوار تتحرّك بفيزياء، وشريط الرئيسية بأخرى، والإشعار بثالثة.
 * هذا الملف يجمع الفيزياء في مكان واحد؛ الملفّان أعلاه يشتقّان منه الآن.
 *
 * القيم هنا **مطابقة تماماً** لما استقرّ عليه ضبط الرئيسية بالقياس —
 * التوحيد معماري لا سلوكي، ولم يتغيّر إحساس أي شاشة بسببه.
 */

/**
 * نسبة التخميد ζ = damping ÷ (2·√(stiffness·mass)).
 *   ζ ≈ 0.92–0.96 → انطلاق حاسم، انزلاق سريع، استقرار مغناطيسي بلا ارتداد مرئي.
 *   ζ ≥ 1        → وصول بلا تجاوز لكن نهايته تبدو «متوقّفة».
 *   ζ < 0.85     → ارتداد مرئي ← مرفوض في كل التطبيق.
 */
export const spring = {
  /**
   * انزلاق الصفوف المكانية — الأثقل. ζ≈0.98
   *
   * شُدَّت الصلابة 340 ← 420 لتدخل زمنَ التركيز في نطاق المرجع.
   * الحساب: ωₙ = √(k/m) = √(420/0.85) = 22.2 rad/s، وζ = c/(2√(k·m)) =
   * 37/37.8 = 0.98 — فلا ارتداد. وزمن الاستقرار ‏4/(ζ·ωₙ) ينزل من
   * **206ms إلى 184ms**، أي داخل 150–200ms التي يحدّدها المرجع لإبراز
   * التركيز، وكان خارجها.
   *
   * ولأنّ هذا النابض يقود الصفّ وحقل الطاقة ومرساة العنوان ومحاذاة البطل
   * معاً، فالتسريع يسري على المنظومة كلّها بشخصية واحدة — وهو المقصود.
   */
  navigation: { type: "spring", stiffness: 420, damping: 37, mass: 0.85, restDelta: 0.02 },
  /** تبدّل هندسة عنصر (بلاطة تتمدّد/تنكمش). ζ≈0.95 */
  tile: { type: "spring", stiffness: 380, damping: 33, mass: 0.8, restDelta: 0.05 },
  /** مؤشّرات التركيز المشتركة — أليَن قليلاً فتتخلّف بقدر غير محسوس. ζ≈0.92 */
  focus: { type: "spring", stiffness: 360, damping: 30, mass: 0.78, restDelta: 0.02 },
  /** حركات صغيرة داخل عنصر (رمز داخل بلاطة). ζ≈0.94 */
  icon: { type: "spring", stiffness: 440, damping: 33, mass: 0.7 },
  /** نوافذ وطبقات عمق — أبطأ لأن كتلتها البصرية أكبر. ζ≈0.97 */
  overlay: { type: "spring", stiffness: 310, damping: 34, mass: 0.9 },
  /**
   * ضغط وتغذية راجعة فورية — **النابض الوحيد المسموح له بالرِجعة**.
   *
   * المرجع يتناقض ظاهرياً: قسم «الفيزياء» يوجب تخميداً حرجاً بلا ارتداد،
   * وقسم «الاستقرار الدقيق» يطلب تجاوزاً 5–10% ثم استقراراً في 100–200ms.
   * والحلّ أنّ الأمرين يخصّان حدثين مختلفين: **السفر** يجب أن يصل بلا
   * ارتداد (وإلّا اهتزّ الانتباه)، و**الإفلات** يستحقّ رِجعةً واحدة تؤكّد
   * أنّ الجسم عاد بنفسه لا أنّ قيمةً أُعيدت إلى مكانها.
   *
   * فبقيت نوابض السفر كلّها عند ζ ≈ 0.95–1، وهبط هذا وحده:
   *   ζ = 24 ÷ (2·√(520·0.6)) = 24 ÷ 35.3 = **0.68**
   *   التجاوز = e^(−πζ/√(1−ζ²)) = **5.4%**  ← داخل 5–10%
   *   زمن الاستقرار = 4/(ζ·ωₙ) = 4/(0.68·29.4) = **200ms** ← داخل النطاق
   *
   * وكان ζ = 0.85 أي تجاوزاً قدره **0.63%** — رقمٌ لا تراه عين، فكان
   * «الاستقرار الدقيق» مكتوباً في النيّة وغائباً عن الشاشة.
   */
  press: { type: "spring", stiffness: 520, damping: 24, mass: 0.6 },
} as const;

