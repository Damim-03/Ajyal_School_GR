import { geometry } from "./tokens";
import type { TileMetrics } from "./useTileMetrics";

/**
 * **هندسةُ الشريط المكاني — دوالُّ خالصة، وهي مصدرُ الحقيقة الوحيد.**
 *
 * مفصولةٌ عن `SpatialNavRow` لسببين:
 *
 *   • **تُختبَر.** القاعدةُ التي يقوم عليها النظام كلُّه («البلاطةُ
 *     المطلوبة تقف تحت الإطار بالضبط») يجب أن تكون قابلةً للإثبات
 *     بالحساب لا بالنظر — انظر `rail-geometry.test.ts`. وانكسارُها لا
 *     يُرى خطأً بيّناً بل «انزياحاً بسيطاً» يُظنّ مقصوداً.
 *   • **ملفُّ المكوّن يبقى مكوّناً.** تصديرُ دوالٍّ منه يكسر التحديثَ
 *     السريع في التطوير (`react-refresh`).
 */

/**
 * إزاحةُ الصفّ اللازمة ليقف الموضع `position` تحت المرساة.
 *
 * عند الاستقرار كلُّ البلاطات `compact` إلّا المركَّزة فهي `focused`،
 * فمركزُ البلاطة رقم i من أوّل الصفّ هو بالضبط:
 *
 *   center(i) = i · (compact + gap) + focused / 2
 *
 * ولا يُقرأ من DOM شيء — لا `offsetWidth` (وهو مقودٌ بنابضٍ جارٍ فيقرأ
 * تخطيطاً عابراً)، ولا `getBoundingClientRect` (وهو يعكس التحويل الجاري
 * فيصير الحسابُ تزايدياً).
 *
 * **و`position` كسريٌّ عمداً.** فالاستيفاءُ الخطّي بين مركزين متتاليين
 * يطابق الهندسةَ الحقيقية أثناء السفر مطابقةً تامّة: حين تكون الطاقة في
 * منتصف الطريق تتقاسم البلاطتان التمدّدَ (‏0.5 لكلٍّ منهما)، ومركزُ نقطة
 * التركيز عندئذٍ يساوي استيفاءَ الطرفين. فلا يتخلّف الصفُّ عن الإطار في
 * أيّ لحظةٍ من الرحلة، ولا يحتاج ذلك مزامنةً ولا قياساً.
 */
export const railTravel = (
  position: number,
  m: Pick<TileMetrics, "compact" | "focused" | "gap">,
  anchor: number,
) => position * (m.compact + m.gap) + m.focused / 2 - anchor;

/**
 * مركزُ الإطار من حافّة بداية القراءة داخل صندوق محتوى العارض.
 *
 * نسبةٌ لا بكسلات (§32/§54): تتبع العرض من 1366 إلى 3840 بلا رقمٍ يُضبط
 * لكلّ مقاس.
 */
export const focusAnchorPx = (contentWidth: number) =>
  contentWidth * geometry.focusAnchor;

/** الصندوقُ الكامل للإطار — البلاطةُ المركَّزة زائدَ إزاحته من كلّ جهة. */
export const focusFrameBox = (focusedSize: number) =>
  focusedSize * (1 + geometry.ringOffsetRatio * 2);
