const CURVE = {
  edge: 0.82,       // الحافّة أوّل ما يستجيب — تعريف الشكل يسبق ملأه
  innerLight: 0.9,
  lift: 1,          // المرجع
  tint: 1,
  reflection: 1.25,
  halo: 1.55,       // البيئة آخر ما يعترف — وأبطأ ما يهدأ
  icon: 1.6,        // الرمز يتبع حاويته
} as const;

/** وصف كامل لسطح البلاطة عند شدّة تركيز معيّنة. */
export interface TileSurface {
  /** شفافية تدرّج القسم فوق المادّة الأساس. */
  tint: number;
  /** شدّة ضوء الحافّة الداخلي. */
  edge: number;
  /** شفافية طبقة ظلّ الارتفاع فوق ظلّ الراحة. */
  shadowLift: number;
  innerLight: number;
  lift: number;
  reflection: number;
  /** انزياح الانعكاس الأساسي (نسبة مئوية) — تُضاف إليه إزاحة الكاميرا. */
  sheen: number;
  halo: number;
  haloScale: number;
  iconScale: number;
  iconLift: number;
}

const clamp01 = (v: number) => Math.min(1, Math.max(0, v));

export function tileSurface(intensity: number): TileSurface {
  const i = clamp01(intensity);
  const p = (c: number) => Math.pow(i, c);

  return {
    tint: p(CURVE.tint),
    edge: 0.42 + 0.58 * p(CURVE.edge),
    shadowLift: p(CURVE.lift),
    innerLight: 0.35 + 0.65 * p(CURVE.innerLight),
    lift: p(CURVE.lift),
    reflection: p(CURVE.reflection),
    /* يزحف عبر السطح مع وصول الطاقة ومغادرتها. */
    sheen: -11 + 22 * p(CURVE.reflection),
    halo: p(CURVE.halo),
    /* تتّسع قليلاً وهي تستقبل: ضوء بيئي يتنفّس، لا دائرة تُضاء. */
    haloScale: 0.9 + 0.1 * p(CURVE.halo),
    iconScale: 1 + (geometry.iconSelectedScale - 1) * p(CURVE.icon),
    iconLift: depth.iconLift * p(CURVE.icon),
  };
}

