import { create } from "zustand";

/**
 * **الطاقة — نيّةٌ تُعلَن من أيّ مكان، وشاشةٌ واحدةٌ تُنفّذها.**
 *
 * زرُّ الطاقة يعيش في شاشة اختيار المستخدم، وشاشةُ الإطفاء يجب أن تعلوَ
 * التطبيقَ كلَّه — بما فيه الشاشةُ التي ضُغط الزرُّ فيها. ولو رسمها
 * الزرُّ في موضعه لصارت طبقةً ملءَ الشاشة ابناً لصفٍّ من الأزرار، وورثت
 * سياقَ تكديسه وشفافيّتَه وانسحابَه.
 *
 * فيُعلَن الطلبُ هنا، ويُرسم في `App` فوق الشجرة كلِّها. ومتجرٌ لا
 * `Context` للسبب الذي جعل بقيّةَ متاجر هذا المشروع كذلك: المُعلِنُ
 * والراسمُ في شجرتين متباعدتين، ومزوّدٌ يلفّهما كان سيُعيد عرضَ التطبيق
 * عند كلّ تبدّل.
 */

export type PowerAction = "restart" | "off";

interface PowerState {
  /** `null` = لا شيء يجري. */
  action: PowerAction | null;
}

export const usePower = create<PowerState>()(() => ({ action: null }));

/**
 * طلبُ إطفاءٍ أو إعادةِ تشغيل.
 *
 * **ولا رجعةَ بعدها**: الشاشةُ تعلو وتُغلق الطريق. وذلك مقصود — الفعلُ
 * نفسُه لا رجعةَ فيه، وزرُّ «تراجع» فوق شاشةٍ تقول «جارٍ الإغلاق» يكذب
 * على من يقرؤه. والتأكيدُ يقع **قبلها** في نافذة الطاقة.
 */
export const requestPower = (action: PowerAction) => usePower.setState({ action });
