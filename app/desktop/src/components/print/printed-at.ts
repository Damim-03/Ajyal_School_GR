/**
 * ساعةُ تحرير الورقة مع تاريخها.
 *
 * كان المكتوب تاريخاً وحده: «حُرِّر في 18/08/2026». والكشف الواحد يُطبع
 * أكثرَ من مرّة في اليوم — يُسحب صباحاً، ثمّ يُسجَّل حضورٌ أو تُدفع
 * حقوق، فيُعاد سحبُه. فإذا اجتمعت نسختان على الطاولة بالتاريخ نفسه لم
 * يُعرف أيُّهما الأحدث، والفرق بينهما اسمٌ سُدِّد أو حصةٌ دُوِّنت.
 *
 * والساعة تفصل بينهما. وترتيبُها بعد التاريخ لأنّ الورقة تُؤرشف باليوم
 * أوّلاً، ثمّ يُنظر في الساعة عند التنازع.
 *
 * و`fr-DZ` هو ما تكتبه الإدارة هنا: 18/08/2026 لا 8/18/2026 —
 * والساعةُ أربعٌ وعشرون لا صباحاً ومساءً.
 */
export const printedStamp = (at: Date = new Date()) =>
  at.toLocaleString("fr-DZ", {
    day: "2-digit",
    month: "2-digit",
    year: "numeric",
    hour: "2-digit",
    minute: "2-digit",
    hour12: false,
  });
