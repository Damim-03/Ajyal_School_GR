/**
 * رمزُ الكشف على الورقة — تحت سطر التحرير.
 *
 * الورقة تُطبع وتُسلَّم للأستاذ ثمّ تعود إلى الإدارة بعد أسبوع، وقد
 * اجتمع على الطاولة عشرون كشفاً ترويستُها واحدة: المؤسسة والسنة
 * والعنوان. والفرق مادةٌ وفوجٌ ورقمُ شهرٍ في سطرٍ صغير — فتُقرأ الورقة
 * ثمّ يُبحث عن كشفها في الشاشة باختيار خمسة مرشِّحات.
 *
 * والمشفَّر معرّفُ الكشف نفسه: لا حقلَ جديد في القاعدة ولا هجرة، و
 * `GET /attendance-sheets/:id` يفتحه بمسحةٍ واحدة.
 *
 * والنصُّ تحته ليس زينة: هو المخرج حين يعجز الماسح — ورقةٌ انثنت أو حبرٌ
 * شحّ — فيُنسخ باليد إلى حقل البحث.
 */

import { Barcode } from "./Barcode";

export function SheetBarcode({ code }: { code: string }) {
  if (!code) return null;

  return (
    <span className="sheet-print-code">
      <Barcode value={code} height={40} fit />
      <span className="sheet-print-code-text">{code}</span>
    </span>
  );
}
