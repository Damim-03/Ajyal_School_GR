/**
 * خانةُ إمضاءٍ على ورقةٍ تُطبع.
 *
 * كان الإمضاء سطراً واحداً في وسط الورقة: «إمضاء الأستاذ ......... إمضاء
 * الإدارة .........». وهو يكفي علامةً ولا يكفي وثيقة: لا إقرارَ فوقه
 * يقول ما يُمضى عليه، ولا موضعَ للختم، والنقاطُ تُكتب فوقها لا تحتها
 * فيخرج الاسم مشطوباً.
 *
 * فصارت خانةً على صيغة المراسلة الإدارية الجزائرية:
 *
 *     أنا الممضي أسفله
 *       مدير المؤسسة
 *
 *     ──────────────────
 *      الإمضاء والختم
 *
 * والفراغُ بين الصفة والخطّ خمسة عشر مليمتراً — يدُ الممضي تحتاجها،
 * والخطُّ تحتها لا فوقها فيقع الإمضاء في الفراغ لا على الحبر.
 */

export function PrintSignature({
  role,
  seal = true,
  width = "68mm",
}: {
  /** الصفة تحت الإقرار — «مدير المؤسسة»، «الأستاذ» */
  role: string;
  /** الختمُ للإدارة وحدها — والأستاذ يُمضي ولا يختم */
  seal?: boolean;
  width?: string;
}) {
  return (
    <div style={{ width, textAlign: "center" }}>
      <span style={{ display: "block", fontSize: "3.2mm", fontWeight: 800 }}>
        أنا الممضي أسفله
      </span>

      <span
        style={{
          display: "block",
          marginTop: "1mm",
          fontSize: "2.9mm",
          fontWeight: 700,
        }}
      >
        {role}
      </span>

      <span
        style={{
          display: "block",
          marginTop: "15mm",
          borderTop: "0.3mm solid #000",
          paddingTop: "1.5mm",
          fontSize: "2.8mm",
          fontWeight: 600,
        }}
      >
        {seal ? "الإمضاء والختم" : "الإمضاء"}
      </span>
    </div>
  );
}
