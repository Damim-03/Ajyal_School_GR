/**
 * هوية المستخدم البصرية — مصدر واحد لشاشة اختيار المستخدم والدخول والرئيسية.
 *
 * الغرض استمرارية بصرية: الأفاتار الذي اختاره المستخدم في شاشة الدخول هو
 * نفسه الذي يجده في ترويسة الرئيسية — نفس التدرّج ونفس الحرف. لو حسبت كل
 * شاشة لونها بنفسها لانكسر الإحساس بأنه «هو» انتقل معك إلى الداخل.
 *
 * كانت هذه اللوحة محبوسة داخل LoginPage، فلم تكن الرئيسية تعرف شيئاً عنها.
 */

/** إشباع وسطوع مخفوضان عمداً كي تندمج مع البيئة الداكنة. */
export const AVATAR_GRADIENTS = [
  "linear-gradient(135deg,#9d4467,#5d2743)",
  "linear-gradient(135deg,#41648f,#22384f)",
  "linear-gradient(135deg,#3f7d5c,#204536)",
  "linear-gradient(135deg,#9a6f42,#523a22)",
  "linear-gradient(135deg,#65508c,#332552)",
  "linear-gradient(135deg,#3d7180,#1f414b)",
] as const;

/**
 * تدرّج ثابت لكل اسم. الاشتقاق من الاسم نفسه (لا من ترتيبه في قائمة)
 * يضمن أن يحصل المستخدم على لونه ذاته في كل شاشة وفي كل جلسة.
 */
export function avatarGradient(username: string): string {
  let h = 0;
  for (let i = 0; i < username.length; i++) h = (h * 31 + username.charCodeAt(i)) >>> 0;
  return AVATAR_GRADIENTS[h % AVATAR_GRADIENTS.length];
}

/**
 * الظلّ الافتراضي حين لا صورة — رأسٌ وكتفان، أنثويُّهما بشعرٍ يتجاوز
 * الرأس إلى ما دون الأذنين.
 *
 * الغرض أن يُقرأ الجنس من البعيد كما في فيسبوك: صفٌّ من ثلاثين طالباً
 * بلا صور كان ثلاثين حرفاً متشابهاً، والفرقُ بين «كير مهدي» و«كير مهدي
 * أنس» يحتاج قراءةَ السطر كلِّه. والظلُّ يُميّز قبل القراءة.
 *
 * المجهول يأخذ الشكل المحايد (نفسَ الذكوريّ بلا شعر) لا علامةَ استفهام:
 * أفاتارٌ ينطق «لا أعرف جنسك» أسوأ من أفاتارٍ صامت.
 */
export type AvatarGender = "MALE" | "FEMALE";

/** كتفان يبلغان حافّة الدائرة السفلى — الصدر مقصوصٌ لا معلَّق في الفراغ. */
const SHOULDERS =
  "M2.4 24.6C2.4 18.8 6.7 14.6 12 14.6s9.6 4.2 9.6 10z";

/**
 * الشعر: غلافٌ على شكل حرف C يطوّق الرأس وينزل خصلتين إلى y≈16 حيث
 * يلتقيان الكتفين — وذلك النزولُ وحده هو ما يُفرّق الشكلين في 32 بكسل،
 * فالعرضُ الزائد فوق الرأس يبتلعه تدويرُ الدائرة.
 *
 * وحافّتُه الداخلية **داخل** دائرة الرأس عمداً (8.5,11.2 مثلاً تبعد
 * 4.48 عن مركزٍ نصفُ قطره 4.6): الشكلان بلونٍ واحد فالتداخل يوحّدهما،
 * وأوّلُ نسخةٍ تركتْ بينهما 0.4 وحدة فبدت الخصلتان أذنين معلَّقتين.
 */
const FEMALE_HAIR = [
  "M12 1.6",
  "C7.9 1.6 4.6 4.7 4.6 8.8",
  "C4.6 11.9 5.3 14.4 6.1 16.3",
  "C6.5 17.2 7.9 16.9 8 15.9",
  "C8.1 14.4 8.3 12.6 8.5 11.2",
  "C9.3 8.5 10.5 6.9 12 6.4",
  "C13.5 6.9 14.7 8.5 15.5 11.2",
  "C15.7 12.6 15.9 14.4 16 15.9",
  "C16.1 16.9 17.5 17.2 17.9 16.3",
  "C18.7 14.4 19.4 11.9 19.4 8.8",
  "C19.4 4.7 16.1 1.6 12 1.6",
  "Z",
].join("");

/** الرأس والكتفان واحدٌ في الحالتين — الشعرُ وحده هو الفارق. */
export function avatarSilhouette(gender?: AvatarGender | null) {
  return {
    head: { cx: 12, cy: 8.4, r: 4.6 },
    hair: gender === "FEMALE" ? FEMALE_HAIR : null,
    shoulders: SHOULDERS,
  };
}

