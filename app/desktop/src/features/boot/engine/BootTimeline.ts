import {
  PHASE_AT, PHASE_ORDER, REDUCED_SCALE, SEED_HOLD, TOTAL, type BootPhase,
} from "./boot.config";

/**
 * **جدولُ الإقلاع — دالّةٌ خالصة في الزمن، لا سلسلةُ مؤقّتات.**
 *
 * القاعدةُ التي يفرضها هذا الملفّ: `frameAt(t)` تُعطي المشهدَ كاملاً عند
 * أيّ لحظة، بلا حالةٍ محفوظةٍ ولا تراكم. ونتائجُ ذلك ثلاث:
 *
 * ① **حتميّةٌ تامّة** (§35). التشغيلُ نفسُه يُخرج المشهدَ نفسَه، لأنّ
 *   الزمنَ هو المدخلُ الوحيد. ولا شيء يعتمد على «كم إطاراً مرّ».
 *
 * ② **قابليّةُ القفز والمقاطعة** (§4). تقليلُ الحركة يضرب الزمنَ في
 *   معامل، والتخطّي يقفز به إلى النهاية — بلا أن يُترك طورٌ نصفَ
 *   منفَّذ. ولو كانت الحالةُ متراكمةً لوجب أن يُعاد تشغيلُ ما فات.
 *
 * ③ **إطارٌ مفقودٌ لا يُفسد شيئاً.** جهازٌ تعثّر فقفز 200ms يقرأ المشهدَ
 *   الصحيح عند اللحظة الجديدة، لا مشهداً تخلّف بمقدار ما فات.
 *
 * **ولا `setTimeout` في النظام كلِّه.** المحرّكُ يقرأ ساعتَه من
 * `performance.now`، وReact يُخطَر بتبدّل **الطور** وحده — لا بكلّ إطار
 * (§2).
 */

/* ============================================================
 * منحنيات
 * ============================================================ */

const clamp01 = (v: number) => (v < 0 ? 0 : v > 1 ? 1 : v);

/** استيفاءٌ خطّيٌّ مكبوح بين لحظتين. */
const at = (t: number, from: number, to: number) =>
  to === from ? (t >= to ? 1 : 0) : clamp01((t - from) / (to - from));

/** نعومةٌ عند الطرفين — مشتقّتُها صفرٌ فيهما، فلا انكسارَ يُرى. */
const smooth = (x: number) => {
  const v = clamp01(x);
  return v * v * (3 - 2 * v);
};

/** نبضةٌ تصعد ثمّ تهبط بين ثلاث لحظات. */
const pulse = (t: number, a: number, peak: number, b: number) =>
  t < peak ? smooth(at(t, a, peak)) : 1 - smooth(at(t, peak, b));

/* ============================================================
 * الإطار
 * ============================================================ */

/**
 * حالةُ المشهد عند لحظةٍ ما.
 *
 * وكلُّها قيمٌ متّصلة [0..1] لا أعلامٌ ثنائية: المُظلِّل يقرؤها مباشرةً
 * فيُشتقّ منها كلُّ شيء بلا شرطٍ ولا قفزة. والطورُ (`phase`) للقراءة
 * البشرية ولطبقة React وحدها — لا يقرؤه المُظلِّل.
 */
export interface BootFrame {
  /** الزمنُ المنقضي بالثواني — بعد ضغط «تقليل الحركة» إن كان. */
  time: number;
  phase: BootPhase;
  /** انتهى المشهدُ كلُّه. */
  done: boolean;

  /* ---- طبقةُ الشعار (React) ---- */
  /** ظهورُ الشعار [0..1]. */
  logo: number;
  /** حجابٌ أسودُ فوق كلّ شيء — العتمةُ بين الشعار والحقل. */
  black: number;

  /* ---- طبقةُ الجسيمات (GPU) ---- */
  /** كم من الحقل وُلد [0..1] — تُبنى به النشأة جسيماً بعد جسيم. */
  emerge: number;
  /** الامتدادُ الأفقي [0..1] (§11). */
  spread: number;
  /** حصّةُ الذهب [0..1] (§15). */
  gold: number;
  /** شدّةُ الوهج الإضافية عند الذروة [0..1] (§21). */
  bloom: number;
  /** التبدّدُ [0..1] (§22). */
  disperse: number;
  /** شدّةُ الحقل كلِّه — تخفت ولا تنطفئ عند التسليم. */
  intensity: number;

  /* ---- التسليم ---- */
  /** بيئةُ المصادقة تتشكّل [0..1] (§23). */
  auth: number;
}

/* ============================================================
 * الاشتقاق
 * ============================================================ */

const P = PHASE_AT;

/** الطورُ الحاليّ — آخرُ طورٍ بدأ. */
export function phaseAt(t: number): BootPhase {
  let current: BootPhase = "BOOT_IDLE";

  for (const key of PHASE_ORDER) {
    if (t >= PHASE_AT[key]) current = key;
    else break;
  }

  return current;
}

/**
 * **المشهدُ عند لحظةٍ ما.**
 *
 * ولا حالةَ ولا ذاكرة: كلُّ سطرٍ هنا دالّةٌ في `t` وحدها.
 */
export function frameAt(raw: number, reduced = false): BootFrame {
  /*
   * تقليلُ الحركة يضغط الزمنَ ولا يُلغي المشهد (§32): الترتيبُ معلومةٌ
   * تُقال — شعارٌ، ثمّ عتمة، ثمّ حقلٌ يتذهّب — وإسقاطُه يُفقد المستخدمَ
   * ما يقوله النظامُ عن نفسه.
   */
  const t = reduced ? raw / REDUCED_SCALE : raw;

  return {
    time: t,
    phase: phaseAt(t),
    done: t >= TOTAL,

    /*
     * الشعار: ظهورٌ ناعمٌ ثمّ مكوث ثمّ ذهابٌ إلى العتمة (§6).
     * ولا دورانَ ولا ارتداد — الظهورُ والمقياسُ فقط، ومقياسُه في
     * المكوّن لا هنا (هو شأنُ CSS لا شأنُ الجدول).
     */
    logo: pulse(t, P.LOGO_REVEAL, P.LOGO_HOLD, P.BLACK_TRANSITION),

    /*
     * الحجابُ الأسود: يكتمل في «الصمت البصري» ثمّ ينقشع مع أوّل بذرة.
     * وهو ما يجعل الجسيمَ الأوّل يُرى (§7) — نقطةُ ضوءٍ في عتمةٍ تامّة
     * أوقعُ من نقطةٍ في مشهدٍ نصفِ مضاء.
     */
    black:
      t < P.BLACK_TRANSITION
        ? smooth(at(t, P.LOGO_HOLD, P.BLACK_TRANSITION))
        : 1 - smooth(at(t, P.BLUE_SEED, P.BLUE_GENESIS)),

    /*
     * **النشأةُ مرحلتان لا منحنىً واحداً.**
     *
     * كان `easeOut` على المدى كلِّه — وهو يرتفع **أسرعَ ما يكون في
     * أوّله**. فبعد 120ms من ظهور البذرة كان 15% من الحقل حيّاً: مئاتُ
     * الجسيمات لا واحد. وذلك نقضٌ صريحٌ لـ§8، ولم تكشفه العين — كشفه
     * الاختبار.
     *
     *   ① البذرة  [SEED → GENESIS]  النشأةُ تبقى دون `BIRTH_FLOOR`،
     *      فلا يُولد إلّا الجسيمُ صفر: نقطةُ ضوءٍ واحدةٍ في العتمة.
     *   ② النشأة  [GENESIS → FLOW]  يمتلئ الحقلُ بمنحنىً ناعمٍ يبدأ
     *      من السكون وينتهي إليه.
     */
    emerge:
      t < P.BLUE_GENESIS
        ? SEED_HOLD * smooth(at(t, P.BLUE_SEED, P.BLUE_GENESIS))
        : SEED_HOLD + (1 - SEED_HOLD) * smooth(at(t, P.BLUE_GENESIS, P.BLUE_FLOW)),

    /*
     * الامتدادُ الأفقي يبدأ بعد أن يتماسك القلب، ويستمرّ إلى الذروة:
     * «مادّةٌ مضيئةٌ تسيل» لا «جسيماتٌ تنفجر» (§11).
     */
    spread: smooth(at(t, P.BLUE_FLOW, P.BLUE_GOLD_INTERACTION)),

    /*
     * الذهبُ يظهر تدريجياً على مدى 1.6s — لا تبديلَ لونٍ دفعةً (§15).
     * ويبلغ ذروتَه عند الوهج ثمّ ينحسر قليلاً مع التبدّد.
     */
    gold:
      smooth(at(t, P.GOLD_INTRODUCTION, P.WARM_BLOOM)) *
      (1 - 0.45 * smooth(at(t, P.PARTICLE_DISPERSION, P.AUTH_TRANSITION))),

    /*
     * الوهجُ الدافئ: نبضةٌ حول 7.8s — تصعد في 0.4s وتهبط في 0.6s.
     * الصعودُ أسرعُ من الهبوط عمداً: الضوءُ يُشعل ويخبو، لا يتنفّس.
     */
    bloom: pulse(t, P.BLUE_GOLD_INTERACTION, P.PARTICLE_DISPERSION, P.AUTH_TRANSITION),

    /* التبدّد: دفعٌ إلى الخارج وخفوت — لا `opacity = 0` (§22). */
    disperse: smooth(at(t, P.PARTICLE_DISPERSION, P.AUTHENTICATION_READY)),

    /*
     * **الحقلُ يخفت ولا ينطفئ.**
     *
     * 0.22 عند الاكتمال لا صفر: شاشةُ المصادقة ترث الجوَّ نفسَه (§24)،
     * فبقاءُ أثرٍ أزرقَ حيٍّ تحتها هو ما يجعلها تُقرأ **امتداداً** لما
     * سبقها لا صفحةً جديدة. وانطفاؤه يقطع الخيط.
     */
    intensity: 1 - 0.78 * smooth(at(t, P.PARTICLE_DISPERSION, P.AUTHENTICATION_READY)),

    /* بيئةُ المصادقة تتشكّل بينما ما زال الحقلُ يتبدّد — تراكبٌ لا تعاقب. */
    auth: smooth(at(t, P.AUTH_TRANSITION, P.AUTHENTICATION_READY)),
  };
}

/** المشهدُ بعد انتهائه — يقرؤه مسارُ التخطّي ومسارُ «الإقلاع تمّ سلفاً». */
export const SETTLED: BootFrame = frameAt(TOTAL);
