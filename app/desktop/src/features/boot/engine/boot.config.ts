/**
 * **إعداداتُ محرّك الإقلاع — مصدرٌ واحد لكلّ رقمٍ في المشهد.**
 *
 * لا لونَ ولا مدّةَ ولا عددَ جسيماتٍ يُكتب في مكوّنٍ أو مُظلِّل. والسبب
 * ليس ترتيباً: ضبطُ مشهدٍ كهذا يقع بالعين مرّةً بعد مرّة، وكلُّ رقمٍ
 * متناثرٍ يعني بحثاً في خمسة ملفّات لتغيير درجةِ زُرقة.
 *
 * والأرقامُ هنا **نقيّة**: لا `window` ولا `gl` ولا React. فتُقرأ من
 * المُظلِّل ومن الجدول ومن الاختبار سواءً.
 */

