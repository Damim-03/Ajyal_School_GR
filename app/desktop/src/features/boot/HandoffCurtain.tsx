/**
 * ستارُ التسليم — **شعارُ البرنامج بين المصادقة والرئيسية**.
 *
 * كانت العتبةُ بين الشاشتين قطعاً: كلمةُ المرور تُقبل، فتنسحب شاشةُ
 * الاختيار ربعَ ثانية، وتنكشف الرئيسيةُ من خلفها. أقلُّ من ثانيةٍ يُنقل
 * فيها المستخدمُ من فضاءٍ إلى فضاء، ونغمةُ الاختيار تُقطع لتحلّ محلَّها
 * نغمةُ الرئيسية بلا فاصلٍ يفصل بينهما.
 *
 * **والحركاتُ ثلاثٌ لا اثنتان** — وهذا هو الفرق بين لحظةِ عبورٍ وشاشةِ
 * تحميل:
 *
 *   ① يذهب المحتوى ويبقى المكان — تنسحب واجهةُ كلمة المرور، والفضاءُ
 *     السينمائيّ باقٍ حيّاً يخفت ولا ينطفئ (§4).
 *   ② يحضر الشعارُ **في الفضاء** — فوق ما بقي، لا فوق سواد. وهنا تتلاشى
 *     نغمةُ الاختيار على مهلها.
 *   ③ يذهبان معاً إلى العتمة — ثمّ تُبنى الرئيسيةُ فيها وترتفع عنها.
 *
 * ولذلك القاعُ والشعارُ **طبقتان لا طبقةٌ واحدة**: لو كان الشعارُ ابناً
 * لسطحٍ شفافيتُه هي الستار لَما أمكن أن يُرى وهو شفّاف. فالقاعُ يعتم
 * وحده في حركته، والشعارُ يحضر ويذهب في حركته، ويلتقيان في الثالثة.
 *
 * **وهو خارج الموجّه عمداً** — يُركَّب في `App` فوق الشجرة كلِّها. فطريقا
 * الوصول إلى الرئيسية مختلفان بنيوياً: من الإقلاع تبقى `BootScreen`
 * مركَّبةً فوق الرئيسية وتنسحب، ومن الخروج من الحساب تُبدَّل صفحةُ
 * `SignInPage` في الموجّه فلا يبقى فوق التركيب شيء. ولو رُسم الستارُ
 * داخل إحداهما لغطّى طريقاً وترك الآخر مكشوفاً؛ وهو هنا واحدٌ للطريقين.
 *
 * ولا توقيتَ فيه: الجدولُ يحرّك الحركاتِ الثلاث (‏`motion/home-entrance`)،
 * وهذا المكوّن يرسم ما تقوله الحركةُ ولا يقرّر متى.
 */

import nexschoolLogo from "../../assets/nexschool/nexschool.png";
import { LAYER } from "../../motion/layers";
import { curtain, useCurtain } from "../../motion/home-entrance";

/**
 * قاعُ العتمة — لونُ الفضاء نفسُه لا سوادٌ خالص.
 *
 * السوادُ الخالص يقطع: الفضاءُ السينمائي قاعُه `#04060c`، فانتقالُه إلى
 * `#000` يُقرأ انطفاءً لا انسحاباً. ونقطتان من الزُّرقة تكفيان لأن تبدو
 * العتمةُ عمقاً في المكان نفسِه — لا خروجاً منه.
 */
const GROUND = "#04060c";

/** حضورٌ ينبسط: يبدأ سريعاً ويستقرّ — الشيءُ **يصل** ولا يُقذف. */
const EASE_ENTER = "cubic-bezier(0.22,1,0.36,1)";
/** ذهابٌ متسارع — الجسمُ يغادر ولا يصل. */
const EASE_LEAVE = "cubic-bezier(0.4,0,1,1)";
/** وسطُه شبه خطّي — منحنى الضوء، وبه تعتم البيئةُ وتُضاء (`curve.ambient`). */
const EASE_AMBIENT = "cubic-bezier(0.33,0,0.2,1)";

/**
 * الشعارُ يسبق العتمةَ في الذهاب بقليل.
 *
 * لو ذهبا معاً تماماً لبقي الشعارُ مرئياً على سوادٍ شبهِ تامّ في آخر
 * أجزاء الحركة — فيُقرأ عالقاً لا مغادراً. وثمانون في المئة من مدّة
 * العتمة تُخرجه قبل أن يُغلق السوادُ، فيُقرأ الترتيب: خفَتَ ثمّ أُغلق.
 */
const MARK_LEAVE = Math.round(curtain.blackout * 0.8);

export function HandoffCurtain() {
  const beat = useCurtain();

  const marked = beat === "mark";
  const dark = beat === "black";
  /* قائمٌ بأيّ معنى — يبتلع المؤشّر ما دام كذلك. */
  const up = marked || dark;

  /*
   * **مركَّبٌ دائماً، ومرئيٌّ حين يُطلب.**
   *
   * التركيبُ عند الطلب كان يوجب حالةً محلّيةً تُبقيه حيّاً حتى ينقشع
   * (وإلّا اختفى في إطارٍ واحد) — أي `setState` داخل أثرٍ لأجل توقيتٍ
   * يملكه الجدولُ أصلاً.
   *
   * وبقاؤه مركَّباً يحلّ ذلك ويحلّ معه ما هو أدقّ: `transition` لا يعمل
   * على عنصرٍ رُكّب للتوّ إلّا بعد إطارٍ يُثبَّت فيه وضعُه الابتدائي —
   * وذلك الإطارُ بالذات هو الذي يبتلعه حجبُ الخيط. أمّا هنا فالوضعُ
   * الابتدائي مثبَّتٌ منذ أوّل رسمٍ للتطبيق، فتبديلُ الشفافية يمضي على
   * المُركِّب وحده ولا يعنيه أنّ الخيط محجوب.
   *
   * وكلفتُه لا شيء: سطحان شفّافان لا يلتقطان المؤشّر. بل فيه مكسب —
   * الشعارُ يُجلَب مع أوّل رسمٍ فلا يُطلب في اللحظة التي يجب أن يُرى
   * فيها.
   */
  return (
    <div
      aria-hidden
      className="fixed inset-0 grid select-none place-items-center"
      style={{
        zIndex: LAYER.handoff,
        /*
          يبتلع المؤشّر ما دام قائماً — وإلّا وقعت نقرةٌ على رئيسيةٍ لا
          تُرى بعد. ويُفلته فورَ الأمر بالانقشاع لا بعده: أوّلُ نقرةٍ
          تخصّ الرئيسية (§23).
        */
        pointerEvents: up ? "auto" : "none",
      }}
    >
      {/*
        ===== القاع =====

        شفّافٌ تماماً في حركة الشعار — وهذا هو بيتُ القصيد: الفضاءُ
        السينمائيّ تحته يبقى مرئياً حيّاً، فالشعارُ يحضر **فيه** لا
        فوق سوادٍ حلّ محلَّه.
      */}
      <div
        className="absolute inset-0"
        style={{
          backgroundColor: GROUND,
          opacity: dark ? 1 : 0,
          transition: dark
            ? `opacity ${curtain.blackout}ms ${EASE_AMBIENT}`
            : `opacity ${curtain.out}ms ${EASE_AMBIENT}`,
        }}
      />

      {/*
        ===== الشعار =====

        شعارُ **المنتَج** لا شعارُ المؤسسة — كما في أوّل شاشة الإقلاع
        تماماً. هذه اللحظةُ تقول «هذا هو البرنامج»، وهويةُ المدرسة قيلت
        في شاشة الاختيار قبلها وتُقال في ترويسة الرئيسية بعدها.

        والقياسُ أصغرُ من قياس الإقلاع (‏48vh ← 34vh): ذاك افتتاحٌ يملك
        الشاشة، وهذا عبورٌ بين مشهدين — وشعارٌ بحجم الافتتاح في موضع
        العبور يجعل اللحظةَ تبدو بدايةً أخرى لا وصلاً.
      */}
      <img
        src={nexschoolLogo}
        alt=""
        draggable={false}
        className="relative select-none"
        style={{
          height: "clamp(200px, 34vh, 420px)",
          width: "auto",
          opacity: marked ? 1 : 0,
          /*
            يقترب وهو يحضر، ويواصل الاقترابَ قليلاً وهو يذهب. والاتّجاهُ
            واحدٌ في الحركتين عمداً: جسمٌ يمرّ بنا لا جسمٌ يجيء ويرجع من
            حيث أتى.
          */
          transform: marked ? "scale(1)" : dark ? "scale(1.03)" : "scale(0.965)",
          /*
            توهّجٌ خفيف تحته يفصله عن الفضاء المزدحم بالسُّدُم — بلا حافّةٍ
            مرسومة. ويذهب معه لأنّه منه.
          */
          filter: marked
            ? "drop-shadow(0 0 60px rgba(94,106,255,0.28))"
            : "drop-shadow(0 0 0 rgba(94,106,255,0))",
          transition: marked
            ? `opacity ${curtain.markIn}ms ${EASE_ENTER},` +
              ` transform ${curtain.markIn}ms ${EASE_ENTER},` +
              ` filter ${curtain.markIn}ms ${EASE_ENTER}`
            : `opacity ${MARK_LEAVE}ms ${EASE_LEAVE},` +
              ` transform ${curtain.blackout}ms ${EASE_LEAVE},` +
              ` filter ${MARK_LEAVE}ms ${EASE_LEAVE}`,
        }}
      />
    </div>
  );
}
