/**
 * الانتقالُ بين الشاشات — والاتجاهُ **منطقيٌّ لا يمينٌ ولا يسار** (§47).
 *
 * أوّلُ ما يُكتب في انتقالٍ كهذا `translateX(24px)`. وهو صحيحٌ في
 * الإنجليزية وخاطئٌ في العربية: «الأمام» هناك يمين، وهنا يسار. فشاشةٌ
 * تتقدّم كانت ستبدو راجعةً لنصف مستخدمي هذا البرنامج.
 *
 * فالمكوّنُ يكتب `--nx-dir` من اتجاه المستند، وحركاتُ CSS تضربها في
 * إزاحتها. وتبديلُ اللغة يقلب الرحلةَ كلَّها بلا شرطٍ واحدٍ في مكوّن.
 *
 * **والانتقالُ مبنيٌّ على المفتاح لا على مؤقّت** (§7): تبدّلُ
 * `phase` يُعيد تركيبَ المحتوى بمفتاحٍ جديد فتبدأ الحركة. ولا
 * `setTimeout` يقود شيئاً — الحركةُ نتيجةُ تبدّلِ الحالة، والحالةُ
 * نتيجةُ ردّ الخادم.
 */

import type { ReactNode } from "react";

import { useIsRtl } from "../hooks/useFirstBootState";

export function BootTransition({
  phase,
  children,
}: {
  phase: string;
  children: ReactNode;
}) {
  const rtl = useIsRtl();

  return (
    <div
      key={phase}
      className="nx-enter"
      style={
        {
          height: "100%",
          /*
           * `-1` في العربية: الداخلُ يأتي من جهة «الأمام» المنطقية
           * فينزلق إلى موضعه — وهي في RTL جهةُ اليسار.
           */
          "--nx-dir": rtl ? -1 : 1,
        } as React.CSSProperties
      }
    >
      {children}
    </div>
  );
}
