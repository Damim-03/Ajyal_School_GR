-- كشفُ الطرف الآخر — وإلّا فُتح كشفٌ لا صلة له
--
-- كان الزرّ يمرّر `transferSheetId` في الاتّجاهين، وهو كشفُ الفوج
-- **القديم**. فمن ضغطه من سطر المغادِر ذهب إلى الفوج الجديد بمعرِّف
-- كشفٍ ليس من كشوفه، فسقط الاختيار وفُتح الكشفُ الافتراضي — «الشهر 2»
-- وهو في أفريل، والنقل وقع في أوت.
--
-- فصار لكلّ صفٍّ كشفان: `transferSheetId` كشفُ **فوجه هو** الذي وقع
-- النقل في أثنائه (وبه يُعرف أين يُعرض سطر المغادِر)، و
-- `transferPeerSheetId` كشفُ **الفوج الآخر** في شهر النقل (وإليه يذهب
-- الزرّ). وقد يخلو الثاني إن لم يكن للفوج الآخر كشفٌ في ذلك الشهر،
-- فيفتح الزرّ الفوجَ بلا كشفٍ محدَّد.
-- ------------------------------------------------------

ALTER TABLE `StudentEnrollment` ADD COLUMN `transferPeerSheetId` VARCHAR(191) NULL;
