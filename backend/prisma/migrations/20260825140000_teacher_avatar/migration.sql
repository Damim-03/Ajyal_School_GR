-- وهي غيرُ وثيقة «صورة شمسية»: تلك ورقةٌ سُلّمت للإدارة وتُذكر في
-- قائمة ما سُلّم، وهذه وجهُه الذي يُعرَض ويُطبع. والفصلُ مقصود —
-- الورقةُ تُستبدل بعد سنوات والوجهُ يبقى.
-- ------------------------------------------------------

ALTER TABLE `Teacher` ADD COLUMN `avatar` VARCHAR(191) NULL;
