-- نقلٌ مؤجَّل — يُقرَّر اليوم ويسري عند حدِّ الكشف
--
-- النقلُ في منتصف الكشف يُجزّئ الشهر: فوجٌ درّس خمسَ حصص وآخرُ خمساً،
-- ومجموعُهما عشرٌ في شهرٍ سقفُه ثمان. فيُقرَّر النقل ويُؤجَّل تنفيذُه
-- إلى أوّل كشفٍ جديد: يُكمل الطالب شهره حيث هو، ويبدأ الجديدَ من
-- عموده الأوّل — فلا كشفَ فيه نصفُ طالب، ولا حسابَ يُختلف عليه.
--
-- والتأجيلُ لا يعني الصمت: التسجيلُ يبقى نشطاً وعليه هذه الحقول،
-- فتُقرأ في كشفه ويُقال لمن ينظر «سيُنقل إلى كذا عند انتهاء هذا
-- الكشف». وحين يُنشأ الكشفُ التالي يُنفَّذ من نفسه.
-- ------------------------------------------------------

