-- رمزُ كشف الحضور — ثلاث عشرة خانة
--
-- الورقة تُطبع وتُسلَّم للأستاذ وتعود بعد أسبوع، فتُخلط بغيرها على
-- الطاولة: الترويسة واحدة، والفرق مادةٌ وفوجٌ في سطرٍ صغير. والباركود
-- أسفلها يفتح كشفَها بمسحةٍ واحدة.
--
-- وكان المشفَّر `id` نفسه: خمسةٌ وعشرون محرفاً تُشفَّر في 310 وحدة
-- Code128، فتخرج قضباناً دقيقةً تُتعب الماسح. وثلاث عشرة خانة رقمية
-- تُشفَّر في نحو 110 وحدة — أي قضباناً أثخنَ ثلاثَ مرّات في العرض
-- نفسه، وهو ما تقرؤه الماسحاتُ الرخيصة من أوّل مرّة.
--
-- والطول نفسه المعتمد في الدفعات والإيصالات (`document-number`)،
-- فلا صيغتان في مؤسسة واحدة.
--
-- والصفوف القائمة تُرقَّم هنا لا في سكربت: عمودٌ NOT NULL UNIQUE لا
-- يُضاف على جدولٍ فيه صفوف إلّا بعد ملئه.
-- ------------------------------------------------------

ALTER TABLE `AttendanceSheet` ADD COLUMN `code` VARCHAR(191) NULL;

-- الكشوف القائمة: «9» ثمّ متسلسلٌ من اثنتي عشرة خانة.
--
-- والمتسلسل هنا لا يُفشي شيئاً (‏الكشف ورقةُ حضورٍ لا حركةَ مال)،
-- ويضمن التفرّد بلا رهانٍ على العشوائية. والجديدُ بعد اليوم يأخذ
-- رقماً عشوائياً من `randomDocumentNumber` — وأوّلُ خانةٍ فيه من 1 إلى
-- 9، فالتصادم مع هذه محكومٌ بقيد التفرّد ويُعاد التوليد.
UPDATE `AttendanceSheet` AS s
JOIN (
  SELECT
    id,
    CONCAT('9', LPAD(ROW_NUMBER() OVER (ORDER BY `createdAt`, `id`), 12, '0')) AS num
  FROM `AttendanceSheet`
) AS x ON x.id = s.id
SET s.`code` = x.num;

ALTER TABLE `AttendanceSheet` MODIFY `code` VARCHAR(191) NOT NULL;

CREATE UNIQUE INDEX `AttendanceSheet_code_key` ON `AttendanceSheet`(`code`);
