-- جنس المستخدم
--
-- سببه العرض لا الإدارة: الأفاتار الافتراضي صار ظلَّ شخصٍ
-- بحسب جنسه كما في فيسبوك، والطالب والأستاذ لهما الحقل منذ
-- البدء — وحده المستخدم كان بلا جنس فبقيت حساباته بلا وجه.
--
-- والافتراض MALE لأنّ الصفوف القائمة أُنشئت قبل الحقل ولا
-- سبيل لاستنتاج جنسها؛ تُصحَّح من شاشة «المستخدمون».
-- ------------------------------------------------------

ALTER TABLE `User` ADD COLUMN `gender` ENUM('MALE', 'FEMALE') NOT NULL DEFAULT 'MALE';
