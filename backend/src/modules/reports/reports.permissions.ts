// ======================================================
// صلاحياتُ التقارير — §54 و§67
//
// المشكلةُ التي يحلّها هذا الملف: `REPORT` في النظام اليوم فعلان
// اثنان — `report.view` و `report.export`. أي أنّ مَن يرى تقريرَ
// الحضور يرى سجلَّ التدقيق المالي ومستحقّاتِ الأساتذة. وهذا ما
// ترفضه §54 صراحةً.
//
// والحلُّ الكامل يحتاج صلاحياتٍ جديدة في القاعدة — ترحيلاً وإعادةَ
// بذر. وحتى تُتَّخذ تلك الخطوة، يُعرَّف التدرّجُ هنا **شيفرةً**:
// كلُّ تقريرٍ يعلن ما يلزمه، والحارسُ يترجم ذلك إلى الصلاحيات
// الموجودة فعلاً.
//
// فالفائدة مزدوجة: تدرُّجٌ يعمل اليوم بما هو متاح، وخريطةٌ جاهزة
// تُستبدل بسطرٍ واحد يومَ تُضاف الصلاحيات الدقيقة. ولا يُترك الأمرُ
// لإخفاء عناصر الواجهة — §54 و§67 يشترطان التحقّق في الخادم.
// ======================================================

export type ReportSensitivity =
  /** أرقامٌ تشغيلية: طلبة، حضور، أفواج */
  | "operational"
  /** مالُ الطلبة: فواتير، دفعات، ديون */
  | "financial"
  /** مالُ الأساتذة: تخليص، مستحقّات، دفعات */
  | "teacherFinancial"
  /** سجلُّ التدقيق والإلغاءات وجودة البيانات */
  | "audit";

/**
 * الصلاحيةُ المطلوبة لكلّ درجة.
 *
 * القيمُ الأربع تشير اليوم إلى صلاحياتٍ قائمة. والمرحلةُ التالية
 * تستبدلها بـ`report.view-financial` ونظائرِها بعد الترحيل — وهذا
 * الجدولُ وحده ما يتغيّر حينها.
 *
 * ولا تُشتقّ الصلاحيةُ من اسم التقرير: الاشتقاقُ يجعل إضافةَ تقريرٍ
 * جديد تفتحه للجميع افتراضياً. والجدولُ الصريح يُجبر مَن يضيف
 * تقريراً على أن يقرّر حساسيتَه.
 */
export const SENSITIVITY_PERMISSION: Record<ReportSensitivity, string> = {
  operational: "report.view",

  /*
   * مالُ الطلبة يحتاج اطّلاعاً على الفواتير لا على التقارير وحدها.
   *
   * فمن لا يرى فاتورةً في شاشتها لا يصحّ أن يرى مجموعَها في تقرير
   * — التقريرُ نافذةٌ أخرى على نفس البيانات، والتضييقُ في إحداهما
   * دون الأخرى ثغرةٌ لا سياسة.
   */
  financial: "invoice.view",

  /*
   * مالُ الأساتذة أضيقُ من مال الطلبة: كم يتقاضى كلُّ أستاذ معلومةٌ
   * لا يطّلع عليها من يحصّل من الطلبة.
   */
  teacherFinancial: "settlement.view",

  /*
   * التدقيق للإدارة وحدها — §37. وربطُه بصلاحية المستخدمين لأنّ
   * السجلَّ يكشف مَن فعل ماذا: هو معلومةٌ عن الموظّفين لا عن المال.
   */
  audit: "user.view",
};

/**
 * حساسيةُ كلّ تقرير.
 *
 * التقريرُ الذي يمزج درجتين يأخذ الأضيق. ونظرةُ العموم مثالٌ على
 * ذلك: تعرض أرقاماً تشغيليةً ومالية معاً.
 */
export const REPORT_SENSITIVITY: Record<string, ReportSensitivity> = {
  /*
   * نظرةُ العموم مالية لا تشغيلية.
   *
   * §5 يطلب فيها بطاقاتِ الإيراد والتحصيل والدَّين ومستحقّ
   * الأساتذة. فتصنيفُها «تشغيلية» كان سيجعلها بابَ تسرّبٍ خلفياً:
   * مَن مُنع من التقرير المالي يقرأ مجاميعَه من الشاشة الأولى.
   *
   * والبديلُ الأنظف — عرضُ نظرةِ عمومٍ منقوصة بحسب الصلاحية —
   * يحتاج تجزئةَ الاستجابة، وهي مرحلةٌ تالية. وحتى ذلك الحين
   * الأضيقُ أسلم.
   */
  overview: "financial",
  students: "operational",
  attendance: "operational",

  /*
   * الأكاديميُّ مالِيٌّ لا تشغيلي.
   *
   * جداولُه تحمل أعمدةَ «المفوتر» و«المحصَّل» و«المتبقّي» لكلّ
   * طورٍ ومادّةٍ وفوج. فتصنيفُها تشغيليةً كان سيفتح بابَ تسرّبٍ
   * ثانياً بعد نظرة العموم: من مُنع من التقرير المالي يقرأ
   * توزيعَ الإيراد من شاشة المواد.
   *
   * والأنظفُ أن تُحجب الأعمدةُ المالية وحدها بحسب الصلاحية —
   * وذلك يحتاج تجزئةَ الاستجابة، وهي مرحلةٌ تالية.
   */
  academic: "financial",
  stages: "financial",
  levels: "financial",
  subjects: "financial",
  groups: "financial",
  assignments: "financial",

  /* الحصصُ بلا أعمدةٍ مالية، فتبقى تشغيلية */
  sessions: "operational",
  financial: "financial",
  invoices: "financial",
  payments: "financial",
  receipts: "financial",
  debts: "financial",
  "debt-collections": "financial",
  teachers: "teacherFinancial",
  settlements: "teacherFinancial",
  "teacher-payments": "teacherFinancial",
  "financial-flow": "teacherFinancial",
  allocations: "teacherFinancial",
  audit: "audit",
  cancellations: "audit",
  "data-quality": "audit",
};

/**
 * الصلاحيةُ اللازمة لتقريرٍ بعينه.
 *
 * التقريرُ غيرُ المسجَّل يسقط إلى `audit` — أضيقُ الدرجات.
 *
 * والافتراضُ المتشدّد مقصود: مَن ينسى تسجيلَ تقريرٍ جديد يجد
 * الإدارةَ وحدها تراه، فيُكتشف النسيانُ بشكوى «لا أرى التقرير».
 * ولو كان الافتراضُ متساهلاً لانكشف التقريرُ للجميع ولم يشتكِ أحد.
 */
export const permissionForReport = (reportKey: string): string =>
  SENSITIVITY_PERMISSION[REPORT_SENSITIVITY[reportKey] ?? "audit"];

/** التصدير يشترط صلاحيته فوق صلاحية القراءة — §54 */
export const EXPORT_PERMISSION = "report.export";
